const checks = [];

function presence(id, path, req) {
  checks.push({
    id,
    name: 'V-145-' + id + ': ' + path + ' exists and is non-empty' + (req ? ' (' + req + ')' : ''),
    run() {
      const c = readFile(path);
      if (c === null) return { pass: false, detail: path + ' missing' };
      if (c.trim().length === 0) return { pass: false, detail: path + ' is empty' };
      return { pass: true, detail: path + ' present (' + c.length + ' bytes)' };
    }
  });
}

let n = 0;
for (const [path, req] of PRESENCE_DOCS) {
  presence('PRESENCE-' + (++n), path, req);
}

// === V-145-ARCHIVALDRIFT: corpus-wide NEGATIVE, scoped to markdown LINK syntax (FIX-11) ===
// The ratified invariant (D-25) is that a documentation LINK into .planning/research/ or
// .planning/phases/ is broken by construction once milestone archival moves those paths. A bare
// prose mention in backticks (e.g. a governance changelog citing its decision provenance) is not a
// clickable link and does not 404 post-archival -- it is measured separately and NOT gated here.
// Floor guard: if walkMd finds fewer than 250 files, docs/ itself is missing or truncated, which is
// a FAIL (a null sentinel), never a vacuous 0-hit PASS (T-153-27).
checks.push({
  id: 'ARCHIVALDRIFT',
  name: 'V-145-ARCHIVALDRIFT: no docs/ markdown LINK targets a .planning/research/ or .planning/phases/ path (FIX-11, archival-drift invariant)',
  run() {
    const files = walkMd('docs');
    if (files.length < 250) {
      return { pass: false, detail: 'docs/ walk found only ' + files.length + ' files (expected >= 250) -- treating as a missing-corpus null sentinel, not a vacuous pass' };
    }
    const linkPattern = /\]\([^)]*\.planning\/(research|phases)\//;
    const offenders = [];
    for (const f of files) {
      let c;
      try { c = readFileSync(f, 'utf8'); } catch { continue; }
      if (linkPattern.test(c)) offenders.push(f);
    }
    if (offenders.length > 0) {
      return { pass: false, detail: offenders.length + ' file(s) carry a broken-by-archival planning link: ' + offenders.slice(0, 5).join(', ') };
    }
    return { pass: true, detail: '0 markdown-link references into .planning/research/ or .planning/phases/ across ' + files.length + ' docs/ files' };
  }
});

// === V-145-FRESHNESS: review_by - last_verified <= 60 days on the five corrected docs (FIX-10) ===
checks.push({
  id: 'FRESHNESS',
  name: 'V-145-FRESHNESS: review_by - last_verified <= ' + FRESHNESS_CEILING_DAYS + ' days on the five FIX-10 documents',
  run() {
    const errors = [];
    for (const path of FRESHNESS_DOCS) {
      const c = readFile(path);
      if (c === null) { errors.push(path + ' missing'); continue; }
      const lv = c.match(/^last_verified:\s*(\d{4}-\d{2}-\d{2})/m);
      const rb = c.match(/^review_by:\s*(\d{4}-\d{2}-\d{2})/m);
      if (!lv || !rb) { errors.push(path + ' missing last_verified/review_by frontmatter'); continue; }
      const lvDate = new Date(lv[1] + 'T00:00:00Z');
      const rbDate = new Date(rb[1] + 'T00:00:00Z');
      const days = Math.round((rbDate.getTime() - lvDate.getTime()) / 86400000);
      if (!(days >= 0 && days <= FRESHNESS_CEILING_DAYS)) {
        errors.push(path + ': interval = ' + days + ' days (expected 0..' + FRESHNESS_CEILING_DAYS + ')');
      }
    }
    if (errors.length > 0) return { pass: false, detail: errors.join('; ') };
    return { pass: true, detail: 'all ' + FRESHNESS_DOCS.length + ' documents carry review_by - last_verified <= ' + FRESHNESS_CEILING_DAYS + ' days' };
  }
});

// === V-145-DISTROSWEEP: corrected distro tokens present, superseded token absent (FIX-09) ===
checks.push({
  id: 'DISTROSWEEP',
  name: 'V-145-DISTROSWEEP: Ubuntu 24.04/26.04 present in the prerequisites matrix; Ubuntu 22.04 absent corpus-wide',
  run() {
    const prereq = readFile(PREREQ_LINUX);
    if (prereq === null) return { pass: false, detail: PREREQ_LINUX + ' missing' };
    if (!prereq.includes('24.04')) return { pass: false, detail: 'DISTROSWEEP needle absent: 24.04 not found in ' + PREREQ_LINUX };
    if (!prereq.includes('26.04')) return { pass: false, detail: 'DISTROSWEEP needle absent: 26.04 not found in ' + PREREQ_LINUX };

    const files = walkMd('docs');
    if (files.length < 250) {
      return { pass: false, detail: 'docs/ walk found only ' + files.length + ' files -- treating as a missing-corpus null sentinel' };
    }
    const offenders = [];
    for (const f of files) {
      let c;
      try { c = readFileSync(f, 'utf8'); } catch { continue; }
      if (c.includes('22.04')) offenders.push(f);
    }
    const generator = readFile(GENERATE_DIAGRAMS);
    if (generator !== null && generator.includes('22.04')) offenders.push(GENERATE_DIAGRAMS);
    if (offenders.length > 0) {
      return { pass: false, detail: 'superseded 22.04 token survives in: ' + offenders.slice(0, 5).join(', ') };
    }
    return { pass: true, detail: '24.04 and 26.04 present in ' + PREREQ_LINUX + '; 0 occurrences of 22.04 across docs/ and ' + GENERATE_DIAGRAMS };
  }
});

// === V-145-FROZENREAD: check-phase-59.mjs's ops-index read is the converted frozen form (FIX-12) ===
