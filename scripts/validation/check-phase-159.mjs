// check-phase-159.mjs -- Phase 159 deliverables (HARN -- Harness Close, the v1.22 terminal apex)
//
// Chain-apex of v1.22 -- HARN-04. Ships the v1.22 chain-apex validator: a 111-entry chain spanning
// every integer 48 through 158, HARNESS repointed to v1.22-milestone-audit.mjs. Structural template
// only from check-phase-153.mjs (AUDIT + CHAIN + AUDIT-HARNESS + SELF) -- the chain array and its
// module-load guards are INDEPENDENTLY RE-DERIVED here, never transcribed forward. The three HAZARD
// FIXes present in check-phase-153.mjs are INHERITED as MECHANISM, not re-invented, but every count
// and span string they emit is re-derived at authoring time -- see below. This apex additionally
// carries ONE additive check beyond the predecessor's five categories: V-159-HARN03, which exercises
// the newly-converted (frozen) v1.21-milestone-audit.mjs for real in every invocation including
// nested ones -- the only place in the apex the converted harness is reachable at all, since it is
// not the AUDIT-HARNESS spawn target (D-25). This replaces check-phase-153's C17CARVEOUT-SUCCESSOR
// slot in the same position of the sum, not an eighth term.
// Source of truth: .planning/phases/159-harn-harness-close/159-CONTEXT.md
//   and .planning/phases/159-harn-harness-close/159-PATTERNS.md
//
// CRITICAL -- [48..N-1] invariant: the chain array spans 48..158 (NOT 48..159, which would include
// phase 159 itself, tripping V-159-SELF self-reference FAIL; NOT a truncated range, which would fail
// the length!==111 / terminus!==158 throws). 158 minus 48 plus 1 = 111 entries, GENERATED by
// arithmetic (Array.from), never hand-transcribed. Contiguity on disk was confirmed at authoring time
// (159-EVIDENCE.md Section 18): every integer 48..158 has a corresponding
// scripts/validation/check-phase-{N}.mjs file (the five leaf numbers 154..158 were authored by
// 159-05..159-06 ahead of this apex, per the precondition below).
//
// CRITICAL -- CHAIN_SKIP invariant: CHAIN_SKIP = new Set([]) -- NEVER add entries.
// V-159-SELF hard-asserts CHAIN_SKIP.size === 0 per Phase 68 7b635ca invariant, carried forward
// unchanged into v1.22.
//
// CRITICAL -- CHAIN_EXTRA disjointness guard: CHAIN_EXTRA = [30, 31] carries forward VERBATIM, stays
// outside all three CHAIN_PHASES module-load guards (dedup/length/termini) and outside V-159-SELF's
// dual-invariant, exactly as check-phase-153.mjs keeps it. But CHAIN_EXTRA is declared AFTER those
// three guards, so it is structurally uncoverable by them -- a sidecar member silently absorbed into
// CHAIN_PHASES (or vice versa) would pass all three. This file carries the fourth guard forward:
// assert at module load that every CHAIN_EXTRA member is absent from CHAIN_PHASES. Collapsing
// CHAIN_EXTRA into the span is forbidden.
//
// CRITICAL -- ordering: the AUDIT-HARNESS step's existence-absent branch is a hard FAIL and sits
// BEFORE the NESTED guard, so an ordering slip becomes a recorded FAIL, not a silently skipped
// regression. Ordering is harness, then leaves, then apex -- an apex run before the harness exists
// emits a failure indistinguishable from a real regression.
//
// CRITICAL -- archive-root token (D-29): this apex asserts the LITERAL STRING token 'v1.22-phases'
// (v1.22's own archival root -- where 159-VERIFICATION.md will land when a future
// /gsd-complete-milestone archives v1.22 at the next milestone's close). The resolver's null-vs-
// success behavior is explicitly NOT used as the wrong-token detector: _lib/archive-path.mjs checks
// the LIVE path first and returns success regardless of token correctness before archival --
// proven by counterexample check-phase-125.mjs:86, which carries the wrong ['v1.15-phases'] token and
// has been permanently green with a false detail string for two milestones. Never copy a
// predecessor's token. The archive directory for v1.22 cannot exist while this phase runs --
// archival happens after the phase -- so every in-phase invocation of the AUDIT check takes the live
// branch and SKIP-PASSes regardless of token correctness; the token is verified here as a literal
// string in this apex's own source, the only in-phase check available. The resolver is exercised
// against the archived path only in the post-archival re-run.
//
// CRITICAL -- V-159-HARN03 additive leg (D-25): unlike V-159-AUDIT-HARNESS, this leg is NOT skipped
// under CHECK_PHASE_NESTED=1 -- a frozen harness (v1.21-milestone-audit.mjs, converted to
// frozen-corpus reads at V121 in Plan 159-04) has no evolved corpus to skip for, so re-running it is
// "real and free" (the NESTED-GUARD-SECOND-ORDER-ASYMMETRY deferral's own words). No negative
// substring assertion is written about the v1.22 harness anywhere in this file -- a negative claim
// about a file's current content becomes false the moment that file is next edited, with nothing
// catching the regression (that defect class -- V-140-C17CARVEOUT's now-false scope claim -- already
// exists in this repository and is not to be recreated here).
//
// HAZARD FIX 1 (inherited mechanism) -- explicit maxBuffer on execFileSync: sets
// maxBuffer: 20 * 1024 * 1024 (20 MiB) -- generous headroom for the most verbose single child (the
// AUDIT-HARNESS step running the 16-check v1.22-milestone-audit.mjs --verbose, counted directly off
// the live checks array at authoring time, not copied from any predecessor's stale count) without
// masking a genuinely runaway process. Applied at all three spawn sites -- the chain spawn, the
// harness spawn, and the HARN03 spawn -- because the default overflows into a throw that is not a
// missing-executable throw and therefore becomes a FAIL.
//
// HAZARD FIX 2 (inherited mechanism) -- narrowed missing-child classifier: restricts classification
// to the two unambiguous OS-level signals -- ENOENT (file not found) and shell exit status 127
// (command not found). Everything else -- including a module-load throw from one of THIS file's own
// dedup/length/termini/disjointness guards firing inside a child process -- falls through to FAIL,
// rather than being converted into a green SKIP by a loose two-substring stderr heuristic. That loose
// form is NEVER used here.
//
// HAZARD FIX 3 (inherited mechanism) -- non-existent chain child is a FAIL, not a skip: CHAIN_PHASES
// is a fixed, asserted 111-entry span; a member of it missing from disk is a regression (a deleted
// predecessor validator), not a benign gap. This is why leaves 154-158 MUST be authored before this
// apex -- apex-first would emit five FAILs indistinguishable from a real regression.
//
// Assertion classes:
//   V-159-AUDIT                159-VERIFICATION.md heading-presence via ['v1.22-phases'] resolver
//                               (SKIP-PASS is legitimate pre-close-gate, not a throw)
//   V-159-CHAIN-{48..158}      111 subprocesses; each check-phase-{N}.mjs exits 0 (NESTED-aware)
//   V-159-CHAIN-{30,31}        2 sidecar subprocesses (CHAIN_EXTRA), same shape, disjoint from the span
//   V-159-AUDIT-HARNESS        scripts/validation/v1.22-milestone-audit.mjs exits 0 (current-milestone
//                               harness; NESTED-aware; absent branch precedes the NESTED guard)
//   V-159-HARN03                v1.21-milestone-audit.mjs (frozen, converted) exits 0 and references
//                               withDocsAtClose; NEVER skipped under NESTED (D-25)
//   V-159-SELF                 CHAIN_PHASES does NOT include 159 AND CHAIN_SKIP is empty Set
//                               (dual-invariant)
//
// Executed children: 113 (111 CHAIN_PHASES + 2 CHAIN_EXTRA). Total checks: 117 (1 AUDIT + 113 chain +
// 1 AUDIT-HARNESS + 1 HARN03 + 1 SELF).
// Formula: 1 AUDIT + 111 chain + 2 CHAIN_EXTRA + 1 AUDIT-HARNESS + 1 HARN03 + 1 SELF = 117.
// Expected result triples, exact:
//   117 PASS, 0 FAIL, 0 SKIPPED   -- once 159-VERIFICATION.md exists
//   116 PASS, 0 FAIL, 1 SKIPPED   -- while 159-VERIFICATION.md does not yet exist (AUDIT SKIP-PASSES)
//   115 PASS, 1 FAIL, 1 SKIPPED   -- if run before v1.22-milestone-audit.mjs exists (AUDIT-HARNESS
//                                     FAILs, its existence branch precedes the NESTED guard)
// This apex sets CHECK_PHASE_NESTED=1 on every child it spawns -- it structurally cannot produce, and
// must never be described as producing, an admissible result across a NESTED invocation for the
// CHAIN/AUDIT-HARNESS legs. A nested run of this apex returns a small number of passes, zero
// failures and a large number of skips at exit 0 for those legs -- a result that reads as a pass and
// is NOT one. V-159-HARN03 is the deliberate exception: it reports a real pass in both plain and
// nested runs (D-25). Close evidence is never captured from a nested run of the CHAIN/AUDIT-HARNESS
// legs.
//
// Timeout budgets (inherited mechanism): 600s per-peer (phaseNum >= 67) / 300s per-subprocess, and
// the AUDIT-HARNESS and HARN03 300s timeouts. This apex is NEVER added to its own CHAIN_PHASES --
// that is the exact self-reference V-159-SELF hard-fails on.
//
// Lineage: structural template check-phase-153.mjs (v1.21's apex); chain span, guards and every
// runtime-emitted literal independently re-derived this phase.
//
// Run the apex chain SEPARATELY from any verifier or prose-guard pass -- a link/anchor edit is a
// prose change and has tripped banned-phrase guards after a passed verifier before.
//
// Usage: node scripts/validation/check-phase-159.mjs [--verbose]
// Exit code: 0 if all PASS or SKIPPED; 1 if any FAIL.

import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import process from 'node:process';
import { resolveArchivedPhasePath } from './_lib/archive-path.mjs';
import { execFailDetail } from './_lib/exec-fail-detail.mjs';

const argv = process.argv.slice(2);
const VERBOSE = argv.includes('--verbose');

function readFile(relPath) {
  const abs = join(process.cwd(), relPath);
  if (!existsSync(abs)) return null;
  return readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
}

const HARNESS = 'scripts/validation/v1.22-milestone-audit.mjs';
const HARN03_TARGET = 'scripts/validation/v1.21-milestone-audit.mjs';

// HAZARD FIX 1: explicit maxBuffer (20 MiB) -- see header comment for the chosen-value rationale.
// Applied at all three spawn sites (chain spawn below; harness spawn and HARN03 spawn in Task 2).
const SUBPROCESS_MAX_BUFFER = 20 * 1024 * 1024;

// Phase 159 chain-apex spans every integer 48..158 (158 - 48 + 1 = 111 entries).
// GENERATED by arithmetic, not hand-transcribed.
const CHAIN_START = 48;
const CHAIN_END = 158; // [48..N-1] invariant for N=159: apex EXCLUDES its own phase (159).
const CHAIN_PHASES = Array.from({ length: CHAIN_END - CHAIN_START + 1 }, (_, i) => CHAIN_START + i);

// CHAIN_SKIP topology: empty per Phase 68 7b635ca invariant -- no entries to suppress.
// NEVER add entries: V-159-SELF hard-asserts CHAIN_SKIP.size === 0.
const CHAIN_SKIP = new Set([]);

// De-duplication guard: length + termini asserts alone do not catch a duplicated/dropped interior
// entry. Assert the set of unique values also has exactly 111 members.
if (new Set(CHAIN_PHASES).size !== CHAIN_PHASES.length) {
  throw new Error('check-phase-159 CHAIN_PHASES contains duplicate entries (unique count ' + new Set(CHAIN_PHASES).size + ' !== ' + CHAIN_PHASES.length + ')');
}

// Programmatic bound assertions (fail-loud at module load if the chain topology drifts):
// CHAIN_PHASES must be exactly 111 entries and terminate at 158 (the [48..N-1] invariant for N=159).
if (CHAIN_PHASES.length !== 111) {
  throw new Error('check-phase-159 CHAIN_PHASES length ' + CHAIN_PHASES.length + ' !== 111 (integers 48..158 inclusive)');
}
if (CHAIN_PHASES[0] !== 48 || CHAIN_PHASES[CHAIN_PHASES.length - 1] !== 158) {
  throw new Error('check-phase-159 CHAIN_PHASES must span 48..158 (got ' + CHAIN_PHASES[0] + '..' + CHAIN_PHASES[CHAIN_PHASES.length - 1] + ')');
}

const checks = [];

// V-159-AUDIT: heading-presence check on 159-VERIFICATION.md (SKIP-PASS until the close-gate lands).
// Uses this milestone's OWN, objectively correct archive-root token ['v1.22-phases'] -- asserted as a
// LITERAL STRING here, a deliberate correction away from the predecessor-copied wrong tokens that
// check-phase-119/125/128 carry (frozen, not fixed here). resolveArchivedPhasePath's resolver-null ->
// SKIP-PASS is legitimate pre-close-gate behavior, NOT the silent-wrong bug class D-36 (v1.21
// CONTEXT) guards against -- the resolver checks the LIVE path first and succeeds regardless of
// token correctness before archival, so the archive directory for v1.22 cannot exist while this
// phase runs and every in-phase invocation takes the live branch and SKIP-PASSes regardless of token
// correctness. A WRONG token would only be exposed post-archival, permanently
// (check-phase-125.mjs:86 counterexample). Getting the token objectively right at authoring time --
// verified here as a literal in the source, the only in-phase check available -- is what keeps this
// SKIP-PASS branch honest. The resolver is exercised against the archived path only in the
// post-archival re-run.
const ARCHIVE_ROOT_TOKEN = 'v1.22-phases';
checks.push({
  id: 'AUDIT',
  name: 'V-159-AUDIT: 159-VERIFICATION.md exists and contains Phase 159 verification heading',
  run() {
    const verifPath = resolveArchivedPhasePath(
      '159-harn-harness-close/159-VERIFICATION.md',
      [ARCHIVE_ROOT_TOKEN]
    );
    const verif = verifPath ? readFile(verifPath) : null;
    if (!verif) return { pass: true, skipped: true, detail: '159-VERIFICATION.md not yet authored (PASS-via-skip until the Phase 159 close-gate lands; correct-token resolver-null is legitimate pre-close-gate -- the archive directory cannot exist while this phase runs, so this branch cannot itself confirm the token, only the live-path absence)' };
    if (!/Phase 159/i.test(verif)) {
      return { pass: false, detail: '159-VERIFICATION.md missing "Phase 159" section heading' };
    }
    return { pass: true, detail: '159-VERIFICATION.md exists with Phase 159 verification content' };
  }
});

// CHAIN_EXTRA: carried forward verbatim from check-phase-153.mjs -- NOT part of the arithmetic
// CHAIN_PHASES span and NOT subject to its three module-load guards (dedup/length/termini) above, nor
// to V-159-SELF's two invariants below -- both stay scoped to CHAIN_PHASES/CHAIN_SKIP only.
const CHAIN_EXTRA = [30, 31];

// Guard 159 carries forward from 153: CHAIN_EXTRA is declared AFTER all three CHAIN_PHASES guards
// above, so a sidecar member silently absorbed into (or overlapping) the span would pass all three
// undetected. Assert disjointness explicitly, at module load.
if (!CHAIN_EXTRA.every((n) => !CHAIN_PHASES.includes(n))) {
  throw new Error('check-phase-159 CHAIN_EXTRA overlaps CHAIN_PHASES -- must stay disjoint');
}

// === V-159-CHAIN-NN: chain regression-guards for check-phase-{48..158}.mjs plus the {30,31} sidecar ===
// NESTED-aware optimization (CHECK_PHASE_NESTED=1) prevents polynomial wall-clock blowup when
// peer chain-guards recursively invoke this validator. Preserves standalone semantics.
// isPeer threshold: phaseNum >= 67 -- peer validators run their own chain-guards (600s timeout).
const NESTED = process.env.CHECK_PHASE_NESTED === '1';
for (const phaseNum of [...CHAIN_PHASES, ...CHAIN_EXTRA]) {
  if (CHAIN_SKIP.has(phaseNum)) continue;
  checks.push({
    id: `CHAIN-${phaseNum}`,
    name: `V-159-CHAIN-${phaseNum}: check-phase-${phaseNum}.mjs exits 0 (CHAIN regression-guard)`,
    run() {
      if (NESTED) {
        return { pass: true, skipped: true, detail: 'nested invocation (CHECK_PHASE_NESTED=1): skip recursive chain-guard expansion' };
      }
      const path = `scripts/validation/check-phase-${phaseNum}.mjs`;
      if (!existsSync(join(process.cwd(), path))) {
        // HAZARD FIX 3: a non-existent chain child is a FAIL, not a graceful skip -- the array is a
        // fixed, asserted span; a member missing from disk is a deleted-predecessor-validator regression.
        return { pass: false, detail: path + ' is absent -- deleted predecessor validator regression (a member of the fixed 111-entry CHAIN_PHASES span must exist on disk)' };
      }
      const isPeer = phaseNum >= 67;
      const subTimeout = isPeer ? 600000 : 300000;
      const subEnv = { ...process.env, CHECK_PHASE_NESTED: '1' };
      try {
        execFileSync('node', [path], {
          stdio: 'pipe',
          timeout: subTimeout,
          maxBuffer: SUBPROCESS_MAX_BUFFER,
          cwd: process.cwd(),
          env: subEnv,
        });
        return { pass: true, detail: 'check-phase-' + phaseNum + ' exits 0' + (isPeer ? ' (nested)' : '') };
      } catch (err) {
        const stderr = err.stderr ? err.stderr.toString() : '';
        const stdout = err.stdout ? err.stdout.toString() : '';
        // HAZARD FIX 2: classification narrowed to the two unambiguous OS-level signals only --
        // ENOENT (file not found) and shell exit status 127 (command not found). A generic stderr
        // substring match would convert a real module-load throw -- exactly what this file's own
        // dedup/length/termini/disjointness guards produce -- into a green SKIP, defeating the
        // apex's own primary safeguard. Everything else falls through to FAIL.
        const isMissing = err.code === 'ENOENT' || err.status === 127;
        if (isMissing) return { pass: true, skipped: true, detail: 'node executable unavailable (ENOENT/127) -- skipped' };
        return { pass: false, detail: execFailDetail(stdout, stderr, { n: 500, trim: true, prefix: 'check-phase-' + phaseNum + ' FAIL: ' }) };
      }
    }
  });
}

// === V-159-AUDIT-HARNESS: v1.22-milestone-audit.mjs subprocess exits 0 (current-milestone harness) ===
checks.push({
  id: 'AUDIT-HARNESS',
  name: 'V-159-AUDIT-HARNESS: v1.22-milestone-audit.mjs exits 0 (current-milestone harness)',
  run() {
    if (!existsSync(join(process.cwd(), HARNESS))) {
      // Mirrors HAZARD FIX 3's reasoning: the current-milestone harness is a mandatory, not optional,
      // deliverable of this same close phase -- if it is absent, that is a regression, not a skip.
      // This branch precedes the NESTED guard below: an ordering slip records a FAIL.
      return { pass: false, detail: HARNESS + ' is absent -- current-milestone harness regression' };
    }
    if (NESTED) {
      return { pass: true, skipped: true, detail: 'nested invocation (CHECK_PHASE_NESTED=1): skip AUDIT-HARNESS re-run against evolved corpus' };
    }
    try {
      // HAZARD FIX 1: enlarged buffer applied here too.
      execFileSync('node', [HARNESS], { stdio: 'pipe', timeout: 300000, maxBuffer: SUBPROCESS_MAX_BUFFER, cwd: process.cwd() });
      return { pass: true, detail: 'v1.22-milestone-audit.mjs exits 0 (current-milestone harness)' };
    } catch (err) {
      const stderr = err.stderr ? err.stderr.toString() : '';
      const stdout = err.stdout ? err.stdout.toString() : '';
      const isMissing = err.code === 'ENOENT' || err.status === 127;
      if (isMissing) return { pass: true, skipped: true, detail: 'node executable unavailable (ENOENT/127) -- skipped' };
      return { pass: false, detail: execFailDetail(stdout, stderr, { n: 300, trim: false, prefix: 'harness FAIL: ' }) };
    }
  }
});

// === V-159-HARN03: v1.21-milestone-audit.mjs (frozen, converted) exits 0 and references
// withDocsAtClose -- the ONLY place in this apex the newly-converted harness is exercised for real
// (D-25). Copies the AUDIT-HARNESS leg's spawn/timeout/failure-detail structure but DELIBERATELY
// OMITS the NESTED-skip branch: a frozen harness reads a fixed, materialized V121 snapshot rather
// than the live, evolving corpus, so there is nothing for it to "skip re-auditing" under nesting --
// re-running it is real and free (the NESTED-GUARD-SECOND-ORDER-ASYMMETRY deferral's own words). This
// leg therefore reports a genuine pass in every invocation, plain or nested, partially discharging
// that standing deferral. No negative substring assertion about the v1.22 harness is written anywhere
// in this file (see the header CRITICAL note) -- this check only asserts positive facts about the
// FROZEN v1.21 harness.
checks.push({
  id: 'HARN03',
  name: 'V-159-HARN03: v1.21-milestone-audit.mjs exits 0 and references withDocsAtClose (frozen harness, never skipped under NESTED)',
  run() {
    if (!existsSync(join(process.cwd(), HARN03_TARGET))) {
      // Mirrors HAZARD FIX 3's reasoning: the converted v1.21 harness is a mandatory deliverable of
      // this same close phase (Plan 159-04) -- if it is absent, that is a regression, not a skip.
      return { pass: false, detail: HARN03_TARGET + ' is absent -- HARN03 regression (converted v1.21 harness missing)' };
    }
    // NO NESTED-skip branch here (D-25): a frozen harness has no evolved corpus to skip for.
    try {
      const src = readFile(HARN03_TARGET);
      if (src === null || !src.includes('withDocsAtClose')) {
        return { pass: false, detail: 'HARN03 FAIL: harness converted signature absent (withDocsAtClose not referenced in ' + HARN03_TARGET + ')' };
      }
      execFileSync('node', [HARN03_TARGET], { stdio: 'pipe', timeout: 300000, maxBuffer: SUBPROCESS_MAX_BUFFER, cwd: process.cwd() });
      return { pass: true, detail: 'v1.21-milestone-audit.mjs (frozen, converted) exits 0 and references withDocsAtClose' + (NESTED ? ' (nested invocation -- real pass, no skip)' : '') };
    } catch (err) {
      const stderr = err.stderr ? err.stderr.toString() : '';
      const stdout = err.stdout ? err.stdout.toString() : '';
      const isMissing = err.code === 'ENOENT' || err.status === 127;
      if (isMissing) return { pass: true, skipped: true, detail: 'node executable unavailable (ENOENT/127) -- skipped' };
      return { pass: false, detail: execFailDetail(stdout, stderr, { n: 300, trim: false, prefix: 'HARN03 FAIL: ' }) };
    }
  }
});

// === V-159-SELF: dual-invariant guard (CHAIN_PHASES excludes 159; CHAIN_SKIP empty) ===
// Asserts two invariants:
//   1. CHAIN_PHASES must NOT include 159 (apex [48..N-1] invariant; self-reference is a FAIL)
//   2. CHAIN_SKIP must be empty Set (Phase 68 7b635ca invariant)
checks.push({
  id: 'SELF',
  name: 'V-159-SELF: CHAIN_PHASES does NOT include 159; CHAIN_SKIP is empty Set',
  run() {
    if (CHAIN_PHASES.includes(159)) {
      return { pass: false, detail: 'CHAIN_PHASES includes 159 -- self-reference regression' };
    }
    if (CHAIN_SKIP.size !== 0) {
      const skipList = [...CHAIN_SKIP].join(',');
      return { pass: false, detail: 'CHAIN_SKIP non-empty (' + skipList + ') -- Phase 68 7b635ca empty-Set invariant violated' };
    }
    return { pass: true, detail: 'CHAIN_PHASES = [48..158] (111 entries; 159 absent); CHAIN_SKIP = [] (Phase 68 7b635ca invariant)' };
  }
});

// === Runner loop (verbatim pattern from check-phase-153.mjs) ===
const LABEL_WIDTH = 60;
function padLabel(s) {
  if (s.length >= LABEL_WIDTH) return s + ' ';
  return s + ' ' + '.'.repeat(LABEL_WIDTH - s.length) + ' ';
}

let passed = 0, failed = 0, skipped = 0;
console.log('check-phase-159 -- Phase 159 deliverables (HARN -- Harness Close, the v1.22 terminal apex)\n');
for (const check of checks) {
  let result;
  try { result = check.run(); } catch (e) { result = { pass: false, detail: 'Unexpected error: ' + e.message }; }
  const prefix = '[' + check.id + '/' + checks.length + '] ' + check.name;
  const showDetail = result.detail && (VERBOSE || !result.pass || result.skipped);
  if (result.skipped) {
    skipped++;
    process.stdout.write(padLabel(prefix) + 'SKIPPED' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else if (result.pass) {
    passed++;
    process.stdout.write(padLabel(prefix) + 'PASS' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else {
    failed++;
    process.stdout.write(padLabel(prefix) + 'FAIL -- ' + result.detail + '\n');
  }
}

process.stdout.write('\nResult: ' + passed + ' PASS, ' + failed + ' FAIL, ' + skipped + ' SKIPPED (total checks: ' + checks.length + ')\n');
process.exit(failed > 0 ? 1 : 0);
