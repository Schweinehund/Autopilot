import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

const argv = process.argv.slice(2);
const VERBOSE = argv.includes('--verbose');

function readFile(relPath) {
  const abs = join(process.cwd(), relPath);
  if (!existsSync(abs)) return null;
  return readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
}

// Prose needles can legitimately wrap across a markdown soft line break; flatten whitespace runs to
// a single space before substring matching so a needle is not defeated by where the author wrapped.
function flat(c) {
  return c.replace(/\s+/g, ' ');
}

// Lightweight: NO chain (chain lives only in apex check-phase-153.mjs).
const CHAIN_PHASES = [];
const CHAIN_SKIP = new Set([]);

const DOC_OVERVIEW = 'docs/operations/firmware-bios/00-overview.md';
const DOC_DFCI     = 'docs/operations/firmware-bios/01-windows-dfci.md';

const checks = [];

function presence(id, path, req) {
  checks.push({
    id,
    name: 'V-149-' + id + ': ' + path + ' exists and is non-empty' + (req ? ' (' + req + ')' : ''),
    run() {
      const c = readFile(path);
      if (c === null) return { pass: false, detail: path + ' missing' };
      if (c.trim().length === 0) return { pass: false, detail: path + ' is empty' };
      return { pass: true, detail: path + ' present (' + c.length + ' bytes)' };
    }
  });
}

presence('PRESENCE-OVERVIEW', DOC_OVERVIEW, 'SC#1/SC#2 custody-routing overview');
presence('PRESENCE-DFCI', DOC_DFCI, 'SC#3/SC#4/SC#5 DFCI mechanics guide');

// === V-149-CUSTODY: custody-routing heading, table and three custody positions (SC#1) ===
checks.push({
  id: 'CUSTODY',
  name: 'V-149-CUSTODY: custody-routing heading, table and three custody positions present in ' + DOC_OVERVIEW,
  run() {
    const c = readFile(DOC_OVERVIEW);
    if (c === null) return { pass: false, detail: DOC_OVERVIEW + ' missing' };
    const f = flat(c);
    const required = [
      ['## Who Holds the BIOS Secret', 'custody-routing H2'],
      ['Who holds the BIOS secret', 'table column header'],
      ['Intune holds the secret', 'Dell custody position'],
      ['HP holds the secret, outside your tenant', 'HP custody position'],
      ['you hold the secret', 'Lenovo custody position'],
      ['Lenovo is the only manufacturer whose signing key can sit in infrastructure you own', 'only-vendor RBAC/logging/rotation claim'],
      ['role-based access control (RBAC), audit logging and', 'RBAC/logging/rotation terms'],
    ];
    const missing = required.filter(([needle]) => !f.includes(needle));
    if (missing.length > 0) {
      return { pass: false, detail: 'CUSTODY needle(s) absent: ' + missing.map(([, label]) => label).join(', ') };
    }
    return { pass: true, detail: 'custody-routing heading, table and all three custody positions present in ' + DOC_OVERVIEW };
  }
});

// === V-149-DISJOINT: both native surfaces named, disjointness stated (SC#2) ===
checks.push({
  id: 'DISJOINT',
  name: 'V-149-DISJOINT: both native Intune BIOS surfaces named and disjointness statement present in ' + DOC_OVERVIEW,
  run() {
    const c = readFile(DOC_OVERVIEW);
    if (c === null) return { pass: false, detail: DOC_OVERVIEW + ' missing' };
    const f = flat(c);
    const required = [
      ['## The Two Native Intune BIOS Surfaces', 'two-native-surfaces H2'],
      ['DFCI is the broad surface, and it reaches none of Dell, HP or Lenovo', 'DFCI surface statement'],
      ['BIOS configuration and other settings is the narrow surface, and it reaches Dell alone', 'Templates surface statement'],
      ['they are disjoint: no device is governed by both', 'disjointness statement'],
      ['The file size limit is 2 MB', 'Dell .cctk 2 MB limit'],
    ];
    const missing = required.filter(([needle]) => !f.includes(needle));
    if (missing.length > 0) {
      return { pass: false, detail: 'DISJOINT needle(s) absent: ' + missing.map(([, label]) => label).join(', ') };
    }
    return { pass: true, detail: 'both native surfaces named and disjointness statement present in ' + DOC_OVERVIEW };
  }
});

// === V-149-OEMLIST: nine-OEM canonical list + trailing pending sentence, quoted first-party (SC#3) ===
checks.push({
  id: 'OEMLIST',
  name: 'V-149-OEMLIST: nine-OEM canonical list and trailing "Other OEMs are pending." sentence present in ' + DOC_DFCI,
  run() {
    const c = readFile(DOC_DFCI);
    if (c === null) return { pass: false, detail: DOC_DFCI + ' missing' };
    const oems = ['Acer', 'Asus', 'Dynabook', 'Fujitsu', 'Microsoft Surface', 'Panasonic', 'VAIO', 'Samsung', 'NEC'];
    const missingOem = oems.filter((name) => !c.includes(name));
    if (missingOem.length > 0) {
      return { pass: false, detail: 'OEMLIST needle(s) absent: ' + missingOem.join(', ') };
    }
    if (!c.includes('Other OEMs are pending.')) {
      return { pass: false, detail: 'OEMLIST needle absent: "Other OEMs are pending." trailing sentence not found' };
    }
    if (!c.includes('## OEM Support')) {
      return { pass: false, detail: 'OEMLIST needle absent: "## OEM Support" heading not found' };
    }
    return { pass: true, detail: 'all nine canonical OEM names and the trailing pending sentence present in ' + DOC_DFCI };
  }
});

// === V-149-DISQUALIFIERS: disqualifying prerequisite gate + 24H2 known issue (SC#4) ===
checks.push({
  id: 'DISQUALIFIERS',
  name: 'V-149-DISQUALIFIERS: disqualifying-prerequisite gate and 24H2 Professional known issue present in ' + DOC_DFCI,
  run() {
    const c = readFile(DOC_DFCI);
    if (c === null) return { pass: false, detail: DOC_DFCI + ' missing' };
    const f = flat(c);
    const required = [
      ['## Prerequisites and Disqualifiers', 'disqualifiers H2'],
      ["You can't use DFCI with devices manually registered for Windows Autopilot", 'manual-registration disqualifier'],
      ['requires external attestation of the device’s commercial acquisition through an OEM or a Microsoft CSP partner registration'.replace('’', "'"), 'external-attestation gate'],
      ["DFCI can't currently be configured during the out-of-box experience (OOBE) on devices with Professional editions of Windows 11, version 24H2", '24H2 Professional known issue'],
      ['install KB5046740 or later to enroll in DFCI', '24H2 workaround'],
    ];
    const missing = required.filter(([needle]) => !f.includes(needle));
    if (missing.length > 0) {
      return { pass: false, detail: 'DISQUALIFIERS needle(s) absent: ' + missing.map(([, label]) => label).join(', ') };
    }
    return { pass: true, detail: 'disqualifying-prerequisite gate and the 24H2 Professional known issue plus its workaround present in ' + DOC_DFCI };
  }
});

// === V-149-BRICKING: bricking quotation + two distinct sequence headings (SC#5) ===
checks.push({
  id: 'BRICKING',
  name: 'V-149-BRICKING: DFCI bricking quotation and the two distinct sequence headings present in ' + DOC_DFCI,
  run() {
    const c = readFile(DOC_DFCI);
    if (c === null) return { pass: false, detail: DOC_DFCI + ' missing' };
    const f = flat(c);
    const required = [
      ['Configuring and assigning DFCI profiles can lock the device beyond repair.', 'DFCI bricking quotation'],
      ["Deleting the DFCI profile, or removing a device from the group assigned to the profile doesn't remove DFCI settings", 'delete-removes-nothing quotation'],
    ];
    const missing = required.filter(([needle]) => !f.includes(needle));
    if (missing.length > 0) {
      return { pass: false, detail: 'BRICKING needle(s) absent: ' + missing.map(([, label]) => label).join(', ') };
    }
    if (!c.includes('## Retiring a Device')) {
      return { pass: false, detail: 'BRICKING needle absent: "## Retiring a Device" heading not found' };
    }
    if (!c.includes('## Reusing a Device')) {
      return { pass: false, detail: 'BRICKING needle absent: "## Reusing a Device" heading not found' };
    }
    return { pass: true, detail: 'bricking quotation, delete-removes-nothing quotation and both distinct sequence headings present in ' + DOC_DFCI };
  }
});

// === V-149-BARREDPHRASINGS: "the six" (standalone) and "most business OEMs" absent from BOTH files ===
// File-scoped negative, NOT corpus-wide (per plan instruction): the barred phrasings are barred in
// this domain's own prose, and a corpus-wide negative would be a scope claim the phase never made.
// "the six" excludes the permitted "six-OEM" compound (negative lookahead on the hyphen).
checks.push({
  id: 'BARREDPHRASINGS',
  name: 'V-149-BARREDPHRASINGS: "the six" (standalone) and "most business OEMs" absent from ' + DOC_OVERVIEW + ' and ' + DOC_DFCI,
  run() {
    const reSix = /\bthe six(?!-)\b/i;
    const reBiz = /most business OEMs/i;
    for (const path of [DOC_OVERVIEW, DOC_DFCI]) {
      const c = readFile(path);
      if (c === null) return { pass: false, detail: path + ' missing' };
      const mSix = c.match(reSix);
      if (mSix) {
        return { pass: false, detail: 'BARREDPHRASINGS regression: standalone "the six" found in ' + path + ' (matched "' + mSix[0] + '")' };
      }
      const mBiz = c.match(reBiz);
      if (mBiz) {
        return { pass: false, detail: 'BARREDPHRASINGS regression: "most business OEMs" found in ' + path };
      }
    }
    return { pass: true, detail: 'neither barred phrasing found in either of the two documents this phase shipped (file-scoped, not corpus-wide)' };
  }
});

// === V-149-SELF: dual-invariant guard (CHAIN_PHASES excludes 149; CHAIN_SKIP empty) ===
checks.push({
  id: 'SELF',
  name: 'V-149-SELF: CHAIN_PHASES does NOT include 149; CHAIN_SKIP is empty Set',
  run() {
    if (CHAIN_PHASES.includes(149)) {
      return { pass: false, detail: 'CHAIN_PHASES includes 149 -- self-reference regression' };
    }
    if (CHAIN_SKIP.size !== 0) {
      const skipList = [...CHAIN_SKIP].join(',');
      return { pass: false, detail: 'CHAIN_SKIP non-empty (' + skipList + ') -- Phase 68 7b635ca empty-Set invariant violated' };
    }
    return { pass: true, detail: 'CHAIN_PHASES = [] (lightweight leaf, apex is check-phase-153.mjs); CHAIN_SKIP = [] (Phase 68 7b635ca invariant)' };
  }
});

// === Runner loop (verbatim pattern from check-phase-126.mjs / check-phase-147.mjs / check-phase-148.mjs) ===
const LABEL_WIDTH = 60;
function padLabel(s) {
  if (s.length >= LABEL_WIDTH) return s + ' ';
  return s + ' ' + '.'.repeat(LABEL_WIDTH - s.length) + ' ';
}

let passed = 0, failed = 0, skipped = 0;
console.log('check-phase-149 -- Phase 149 deliverables (Firmware/BIOS Domain -- Overview, DFCI & Surface UEFI)\n');
for (const check of checks) {
  let result;
  try { result = check.run(); } catch (e) { result = { pass: false, detail: 'Unexpected error: ' + e.message }; }
  const prefix = '[' + check.id + '/' + checks.length + '] ' + check.name;
  const showDetail = result.detail && (VERBOSE || !result.pass || result.skipped);
  if (result.skipped) {
    skipped++;
    process.stdout.write(padLabel(prefix) + 'SKIPPED' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else if (result.pass) {
    passed++;
    process.stdout.write(padLabel(prefix) + 'PASS' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else {
    failed++;
    process.stdout.write(padLabel(prefix) + 'FAIL -- ' + result.detail + '\n');
  }
}

process.stdout.write('\nResult: ' + passed + ' PASS, ' + failed + ' FAIL, ' + skipped + ' SKIPPED\n');
process.exit(failed > 0 ? 1 : 0);
