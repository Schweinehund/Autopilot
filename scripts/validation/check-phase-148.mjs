import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

const argv = process.argv.slice(2);
const VERBOSE = argv.includes('--verbose');

function readFile(relPath) {
  const abs = join(process.cwd(), relPath);
  if (!existsSync(abs)) return null;
  return readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
}

// Prose needles can legitimately wrap across a markdown soft line break; flatten whitespace runs to
// a single space before substring matching so a needle is not defeated by where the author wrapped.
function flat(c) {
  return c.replace(/\s+/g, ' ');
}

// Count the eight EAM limitations from the document itself: slice between the section heading and
// the first "**Source:**" line that follows the eighth bullet, then count bold lead-ins that are
// not "**Source:**" lines. This measures the count rather than asserting a remembered figure.
function countEamLimitations(content) {
  const headingIdx = content.indexOf('## Unsupported and Anti-Feature Callouts');
  if (headingIdx === -1) return null;
  const sourceIdx = content.indexOf('**Source:**', headingIdx);
  if (sourceIdx === -1) return null;
  const region = content.slice(headingIdx, sourceIdx);
  const matches = region.match(/^\*\*[^*]+\*\*/gm) || [];
  return matches.length;
}

// Lightweight: NO chain (chain lives only in apex check-phase-153.mjs).
const CHAIN_PHASES = [];
const CHAIN_SKIP = new Set([]);

const DOC_07       = 'docs/operations/patch-management/07-windows-autopatch.md';
const DOC_08       = 'docs/operations/patch-management/08-windows-app-updates.md';
const DOC_COMGMT03 = 'docs/operations/co-management/03-cocmgmt-migration-paths.md';
