import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import process from 'node:process';
import { resolveArchivedPhasePath } from './_lib/archive-path.mjs';
import { execFailDetail } from './_lib/exec-fail-detail.mjs';

const argv = process.argv.slice(2);
const VERBOSE = argv.includes('--verbose');

function readFile(relPath) {
  const abs = join(process.cwd(), relPath);
  if (!existsSync(abs)) return null;
  return readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
}

const HARNESS = 'scripts/validation/v1.19-milestone-audit.mjs';

// HAZARD FIX 1: explicit maxBuffer (20 MiB) -- see header comment for the chosen-value rationale.
const SUBPROCESS_MAX_BUFFER = 20 * 1024 * 1024;

// Phase 138 chain-apex spans every integer 48..137 (137 - 48 + 1 = 90 entries).
// GENERATED by arithmetic, not hand-transcribed or copied from check-phase-134's 86-entry array (D-29).
const CHAIN_START = 48;
const CHAIN_END = 137; // [48..N-1] invariant for N=138: apex EXCLUDES its own phase (138).
const CHAIN_PHASES = Array.from({ length: CHAIN_END - CHAIN_START + 1 }, (_, i) => CHAIN_START + i);

// CHAIN_SKIP topology: empty per Phase 68 7b635ca invariant -- no entries to suppress (D-119-3/D-125-1/D-128-C/GA-2).
// NEVER add entries: V-138-SELF hard-asserts CHAIN_SKIP.size === 0.
const CHAIN_SKIP = new Set([]);

// De-duplication guard: length + termini asserts alone do not catch a duplicated/dropped interior
// entry. Assert the set of unique values also has exactly 90 members.
if (new Set(CHAIN_PHASES).size !== CHAIN_PHASES.length) {
  throw new Error('check-phase-138 CHAIN_PHASES contains duplicate entries (unique count ' + new Set(CHAIN_PHASES).size + ' !== ' + CHAIN_PHASES.length + ')');
}

// Programmatic bound assertions (fail-loud at module load if the chain topology drifts):
// CHAIN_PHASES must be exactly 90 entries and terminate at 137 (the [48..N-1] invariant for N=138).
if (CHAIN_PHASES.length !== 90) {
  throw new Error('check-phase-138 CHAIN_PHASES length ' + CHAIN_PHASES.length + ' !== 90 (integers 48..137 inclusive)');
}
if (CHAIN_PHASES[0] !== 48 || CHAIN_PHASES[CHAIN_PHASES.length - 1] !== 137) {
  throw new Error('check-phase-138 CHAIN_PHASES must span 48..137 (got ' + CHAIN_PHASES[0] + '..' + CHAIN_PHASES[CHAIN_PHASES.length - 1] + ')');
}

const checks = [];

// V-138-AUDIT: heading-presence check on 138-VERIFICATION.md (SKIP-PASS until the close-gate lands).
// Uses this milestone's OWN, objectively correct archive-root token ['v1.19-phases'] -- a deliberate
// correction away from the predecessor-copied wrong token that check-phase-119/125/128 carry (frozen,
// not fixed here). resolveArchivedPhasePath's resolver-null -> SKIP-PASS is legitimate pre-close-gate
// behavior, NOT the silent-wrong bug class D-19 guards against; the post-close-gate confirmatory run
// (Plan 138-06) is what asserts this check is PASS, not SKIP.
checks.push({
  id: 'AUDIT',
  name: 'V-138-AUDIT: 138-VERIFICATION.md exists and contains Phase 138 verification heading',
  run() {
    const verifPath = resolveArchivedPhasePath(
      '138-v118-pin-17th-path-a-lineage-bump-terminal-close/138-VERIFICATION.md',
      ['v1.19-phases']
    );
    const verif = verifPath ? readFile(verifPath) : null;
    if (!verif) return { pass: true, skipped: true, detail: '138-VERIFICATION.md not yet authored (PASS-via-skip until the Phase 138 close-gate lands; corrected-token resolver-null is legitimate pre-close-gate)' };
    if (!/Phase 138/i.test(verif)) {
      return { pass: false, detail: '138-VERIFICATION.md missing "Phase 138" section heading' };
    }
    return { pass: true, detail: '138-VERIFICATION.md exists with Phase 138 verification content' };
  }
});

// === V-138-CHAIN-NN: chain regression-guards for check-phase-{48..137}.mjs ===
// NESTED-aware optimization (CHECK_PHASE_NESTED=1) prevents polynomial wall-clock blowup when
// peer chain-guards recursively invoke this validator. Preserves standalone semantics.
// isPeer threshold: phaseNum >= 67 -- peer validators run their own chain-guards (600s timeout).
const NESTED = process.env.CHECK_PHASE_NESTED === '1';
for (const phaseNum of CHAIN_PHASES) {
  if (CHAIN_SKIP.has(phaseNum)) continue;
  checks.push({
    id: `CHAIN-${phaseNum}`,
    name: `V-138-CHAIN-${phaseNum}: check-phase-${phaseNum}.mjs exits 0 (CHAIN regression-guard)`,
    run() {
      if (NESTED) {
        return { pass: true, skipped: true, detail: 'nested invocation (CHECK_PHASE_NESTED=1): skip recursive chain-guard expansion' };
      }
      const path = `scripts/validation/check-phase-${phaseNum}.mjs`;
      if (!existsSync(join(process.cwd(), path))) {
        // HAZARD FIX 3: a non-existent chain child is a FAIL, not a graceful skip -- the array is a
        // fixed, asserted span; a member missing from disk is a deleted-predecessor-validator regression.
        return { pass: false, detail: path + ' is absent -- deleted predecessor validator regression (a member of the fixed 90-entry CHAIN_PHASES span must exist on disk)' };
      }
      const isPeer = phaseNum >= 67;
      const subTimeout = isPeer ? 600000 : 300000;
      const subEnv = { ...process.env, CHECK_PHASE_NESTED: '1' };
      try {
        execFileSync('node', [path], {
          stdio: 'pipe',
          timeout: subTimeout,
          maxBuffer: SUBPROCESS_MAX_BUFFER,
          cwd: process.cwd(),
          env: subEnv,
        });
        return { pass: true, detail: 'check-phase-' + phaseNum + ' exits 0' + (isPeer ? ' (nested)' : '') };
      } catch (err) {
        const stderr = err.stderr ? err.stderr.toString() : '';
        const stdout = err.stdout ? err.stdout.toString() : '';
        // HAZARD FIX 2: classification narrowed to the two unambiguous OS-level signals only --
        // ENOENT (file not found) and shell exit status 127 (command not found). A generic stderr
        // substring match (the template's loose heuristic) would convert a real module-load throw
        // -- exactly what this file's own dedup/length/termini guards produce -- into a green SKIP,
        // defeating the apex's own primary safeguard. Everything else falls through to FAIL.
        const isMissing = err.code === 'ENOENT' || err.status === 127;
        if (isMissing) return { pass: true, skipped: true, detail: 'node executable unavailable (ENOENT/127) -- skipped' };
        return { pass: false, detail: execFailDetail(stdout, stderr, { n: 500, trim: true, prefix: 'check-phase-' + phaseNum + ' FAIL: ' }) };
      }
    }
  });
}

// === V-138-AUDIT-HARNESS: v1.19-milestone-audit.mjs subprocess exits 0 (current-milestone harness) ===
checks.push({
  id: 'AUDIT-HARNESS',
  name: 'V-138-AUDIT-HARNESS: v1.19-milestone-audit.mjs exits 0 (current-milestone harness)',
  run() {
    if (!existsSync(join(process.cwd(), HARNESS))) {
      // Mirrors HAZARD FIX 3's reasoning: the current-milestone harness is a mandatory, not optional,
      // deliverable of this same close phase -- if it is absent, that is a regression, not a skip.
      return { pass: false, detail: HARNESS + ' is absent -- current-milestone harness regression' };
    }
    if (NESTED) {
      return { pass: true, skipped: true, detail: 'nested invocation (CHECK_PHASE_NESTED=1): skip AUDIT-HARNESS re-run against evolved corpus' };
    }
    try {
      execFileSync('node', [HARNESS], { stdio: 'pipe', timeout: 300000, maxBuffer: SUBPROCESS_MAX_BUFFER, cwd: process.cwd() });
      return { pass: true, detail: 'v1.19-milestone-audit.mjs exits 0 (current-milestone harness)' };
    } catch (err) {
      const stderr = err.stderr ? err.stderr.toString() : '';
      const stdout = err.stdout ? err.stdout.toString() : '';
      const isMissing = err.code === 'ENOENT' || err.status === 127;
      if (isMissing) return { pass: true, skipped: true, detail: 'node executable unavailable (ENOENT/127) -- skipped' };
      return { pass: false, detail: execFailDetail(stdout, stderr, { n: 300, trim: false, prefix: 'harness FAIL: ' }) };
    }
  }
});

// === V-138-SELF: dual-invariant guard (CHAIN_PHASES excludes 138; CHAIN_SKIP empty) ===
// Asserts two invariants:
//   1. CHAIN_PHASES must NOT include 138 (apex [48..N-1] invariant; self-reference is a FAIL)
//   2. CHAIN_SKIP must be empty Set (Phase 68 7b635ca invariant; GA3-C/GA-2 self-disqualifier)
checks.push({
  id: 'SELF',
  name: 'V-138-SELF: CHAIN_PHASES does NOT include 138; CHAIN_SKIP is empty Set',
  run() {
    if (CHAIN_PHASES.includes(138)) {
      return { pass: false, detail: 'CHAIN_PHASES includes 138 -- self-reference regression' };
    }
    if (CHAIN_SKIP.size !== 0) {
      const skipList = [...CHAIN_SKIP].join(',');
      return { pass: false, detail: 'CHAIN_SKIP non-empty (' + skipList + ') -- Phase 68 7b635ca empty-Set invariant violated' };
    }
    return { pass: true, detail: 'CHAIN_PHASES = [48..137] (90 entries; 138 absent); CHAIN_SKIP = [] (Phase 68 7b635ca invariant)' };
  }
});

// === Runner loop (verbatim pattern from check-phase-134.mjs) ===
const LABEL_WIDTH = 60;
function padLabel(s) {
  if (s.length >= LABEL_WIDTH) return s + ' ';
  return s + ' ' + '.'.repeat(LABEL_WIDTH - s.length) + ' ';
}

let passed = 0, failed = 0, skipped = 0;
console.log('check-phase-138 -- Phase 138 deliverables (v1.19 V118 Pin + 17th Path-A Lineage Bump + Terminal Close)\n');
for (const check of checks) {
  let result;
  try { result = check.run(); } catch (e) { result = { pass: false, detail: 'Unexpected error: ' + e.message }; }
  const prefix = '[' + check.id + '/' + checks.length + '] ' + check.name;
  const showDetail = result.detail && (VERBOSE || !result.pass || result.skipped);
  if (result.skipped) {
    skipped++;
    process.stdout.write(padLabel(prefix) + 'SKIPPED' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else if (result.pass) {
    passed++;
    process.stdout.write(padLabel(prefix) + 'PASS' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else {
    failed++;
    process.stdout.write(padLabel(prefix) + 'FAIL -- ' + result.detail + '\n');
  }
}

process.stdout.write('\nResult: ' + passed + ' PASS, ' + failed + ' FAIL, ' + skipped + ' SKIPPED (total checks: ' + checks.length + ')\n');
process.exit(failed > 0 ? 1 : 0);
