// chatty child (e.g. a --verbose harness re-run whose combined stdout+stderr exceeds 1 MiB) into a
// caught FAIL that no hand sweep can reproduce. This file sets maxBuffer: 20 * 1024 * 1024 (20 MiB) --
// generous headroom for the most verbose single child (the AUDIT-HARNESS step running the 17-check
// v1.19-milestone-audit.mjs --verbose plus any of its own recursive chain output) without masking a
