// graceful-skips (pass:true) when a chain child's file is absent, so the apex structurally cannot
// detect a DELETED predecessor validator. CHAIN_PHASES is a fixed, asserted 90-entry span; a member of
// it missing from disk is a regression, not a benign gap. This file returns FAIL in that case.
//
// NOT fixed here (D-00a byte-unchanged doctrine, D-30 scope): check-phase-134.mjs itself keeps all
// three hazards under the frozen-surface invariant -- this file fixes them only in the NEW apex.
//
// Assertion classes:
//   V-138-AUDIT            138-VERIFICATION.md heading-presence via ['v1.19-phases'] resolver (corrected
//                          token; SKIP-PASS is legitimate pre-close-gate, not a throw)
//   V-138-CHAIN-{48..137}  90 subprocesses; each check-phase-{N}.mjs exits 0 (NESTED-aware)
//   V-138-AUDIT-HARNESS    scripts/validation/v1.19-milestone-audit.mjs exits 0 (current-milestone harness; NESTED-aware)
//   V-138-SELF             CHAIN_PHASES does NOT include 138 AND CHAIN_SKIP is empty Set (dual-invariant)
//
// Timeout budgets (D-14): copied forward unchanged from check-phase-134.mjs -- 600s per-peer (phaseNum
// >= 67) / 300s per-subprocess, and the AUDIT-HARNESS 300s timeout. These are the sole coupling point
// with WINDOWS-CLONE-DEEPNEST-TIMEOUT-01, which this milestone deepens to [48..137]; the GHA
// timeout-minutes in the NEW workflow (audit-harness-v1.19-integrity.yml) is a separate, free
// authoring choice, not the same budget. This apex is NEVER added to its own CHAIN_PHASES -- that is
