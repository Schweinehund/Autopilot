// heuristic ALSO matched on generic stderr substrings, which converts a genuine module-load throw
// (e.g. one of THIS file's own dedup/length/termini guards firing inside a child process) into a
// green SKIP -- defeating the apex's own primary safeguard. This file restricts the classification to
// the two unambiguous OS-level signals: the file-not-found error code (ENOENT) and the shell's
// command-not-found exit status (127). Everything else -- including a module-load throw -- falls
// through to FAIL.
//
