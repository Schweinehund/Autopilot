import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

const argv = process.argv.slice(2);
const VERBOSE = argv.includes('--verbose');

function readFile(relPath) {
  const abs = join(process.cwd(), relPath);
  if (!existsSync(abs)) return null;
  return readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
}

// Lightweight: NO chain (chain lives only in apex check-phase-153.mjs).
const CHAIN_PHASES = [];
const CHAIN_SKIP = new Set([]);

const DOC_INDEX        = 'docs/index.md';
const DOC_OPSINDEX     = 'docs/operations/00-index.md';
const DOC_FILENAMEMAP  = 'scripts/pipeline/filename-map.md';
const HUB_FILES = ['docs/common-issues.md', 'docs/quick-ref-l1.md', 'docs/quick-ref-l2.md'];
const SELF_PATH = 'scripts/validation/check-phase-152.mjs';

const RECIPE_TARGET = 'recipes/05-enterprise-update-plan.md';
const QUICKNAV_ANCHOR_RE = /^- \[Device Configuration Recipes\]\(#device-configuration-recipes\)/gm;
const REGISTRY_IDS = ['RE-226', 'RE-227', 'RE-228', 'RE-229', 'RE-230', 'RE-231', 'RE-232', 'RE-233', 'RE-234', 'RE-235', 'RE-236'];

const checks = [];

// === V-152-MASTERHUB-ROW: recipes-table row linking recipes/05-enterprise-update-plan.md ===
checks.push({
  id: 'MASTERHUB-ROW',
  name: 'V-152-MASTERHUB-ROW: recipes-table row linking ' + RECIPE_TARGET + ' present in ' + DOC_INDEX,
  run() {
    const c = readFile(DOC_INDEX);
    if (c === null) return { pass: false, detail: DOC_INDEX + ' missing' };
    const rowRe = new RegExp('^\\|.*\\(' + RECIPE_TARGET.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\)', 'm');
    if (!rowRe.test(c)) {
      return { pass: false, detail: 'MASTERHUB-ROW needle absent: no table row linking ' + RECIPE_TARGET + ' found in ' + DOC_INDEX };
    }
    return { pass: true, detail: 'recipes-table row linking ' + RECIPE_TARGET + ' present in ' + DOC_INDEX };
  }
});

// === V-152-MASTERHUB-QUICKNAV: line-scoped quick-navigation bullet ===
checks.push({
  id: 'MASTERHUB-QUICKNAV',
  name: 'V-152-MASTERHUB-QUICKNAV: quick-navigation bullet (line-scoped) carries "enterprise update plan" in ' + DOC_INDEX,
  run() {
    const c = readFile(DOC_INDEX);
    if (c === null) return { pass: false, detail: DOC_INDEX + ' missing' };
    const matches = c.match(QUICKNAV_ANCHOR_RE) || [];
    if (matches.length !== 1) {
      return { pass: false, detail: 'MASTERHUB-QUICKNAV regression: anchor line match count is ' + matches.length + ', expected exactly 1' };
    }
    const isolatedLine = matches[0];
    // Re-extract the full physical line (the regex above is anchored at line-start but does not
    // capture to line-end), so slice the isolated line out of the source by locating its start
    // and the next newline -- keeping the test scoped to that ONE line, never the whole file.
    const lineStart = c.indexOf(isolatedLine);
    const lineEnd = c.indexOf('\n', lineStart);
    const fullLine = lineEnd === -1 ? c.slice(lineStart) : c.slice(lineStart, lineEnd);
    if (!fullLine.includes('enterprise update plan')) {
      return { pass: false, detail: 'MASTERHUB-QUICKNAV needle absent: "enterprise update plan" fragment not found on the isolated anchor line' };
    }
    return { pass: true, detail: 'anchor line matched exactly once; "enterprise update plan" fragment present on that isolated line' };
  }
});

// === V-152-MASTERHUB-SUBHEADING: "### Firmware and BIOS Governance" in docs/index.md ===
checks.push({
  id: 'MASTERHUB-SUBHEADING',
  name: 'V-152-MASTERHUB-SUBHEADING: "### Firmware and BIOS Governance" present in ' + DOC_INDEX,
  run() {
    const c = readFile(DOC_INDEX);
    if (c === null) return { pass: false, detail: DOC_INDEX + ' missing' };
    if (!/^### Firmware and BIOS Governance$/m.test(c)) {
      return { pass: false, detail: 'MASTERHUB-SUBHEADING needle absent: "### Firmware and BIOS Governance" not found in ' + DOC_INDEX };
    }
    return { pass: true, detail: '"### Firmware and BIOS Governance" sub-heading present in ' + DOC_INDEX };
  }
});

// === V-152-OPSINDEX-HEADING: "## Firmware and BIOS Governance" in docs/operations/00-index.md ===
checks.push({
  id: 'OPSINDEX-HEADING',
  name: 'V-152-OPSINDEX-HEADING: "## Firmware and BIOS Governance" present in ' + DOC_OPSINDEX,
  run() {
    const c = readFile(DOC_OPSINDEX);
    if (c === null) return { pass: false, detail: DOC_OPSINDEX + ' missing' };
    if (!/^## Firmware and BIOS Governance$/m.test(c)) {
      return { pass: false, detail: 'OPSINDEX-HEADING needle absent: "## Firmware and BIOS Governance" not found in ' + DOC_OPSINDEX };
    }
    return { pass: true, detail: '"## Firmware and BIOS Governance" heading present in ' + DOC_OPSINDEX };
  }
});

// === V-152-OPSINDEX-PATCHFRAGS: all four patch path fragments in docs/operations/00-index.md ===
checks.push({
  id: 'OPSINDEX-PATCHFRAGS',
  name: 'V-152-OPSINDEX-PATCHFRAGS: all four patch path fragments present in ' + DOC_OPSINDEX,
  run() {
    const c = readFile(DOC_OPSINDEX);
    if (c === null) return { pass: false, detail: DOC_OPSINDEX + ' missing' };
    const fragments = [
      'patch-management/05-linux-update-delivery.md',
      'patch-management/06-windows-driver-firmware-updates.md',
      'patch-management/07-windows-autopatch.md',
      'patch-management/08-windows-app-updates.md',
    ];
    const missing = fragments.filter((f) => !c.includes(f));
    if (missing.length > 0) {
      return { pass: false, detail: 'OPSINDEX-PATCHFRAGS needle(s) absent from ' + DOC_OPSINDEX + ': ' + missing.join(', ') };
    }
    return { pass: true, detail: 'all four patch path fragments present in ' + DOC_OPSINDEX };
  }
});

// === V-152-OPSINDEX-VERSIONHIST: a Version History row citing INT-04 ===
checks.push({
  id: 'OPSINDEX-VERSIONHIST',
  name: 'V-152-OPSINDEX-VERSIONHIST: Version History row citing INT-04 present in ' + DOC_OPSINDEX,
  run() {
    const c = readFile(DOC_OPSINDEX);
    if (c === null) return { pass: false, detail: DOC_OPSINDEX + ' missing' };
    if (!c.includes('INT-04')) {
      return { pass: false, detail: 'OPSINDEX-VERSIONHIST needle absent: no "INT-04" citation found in ' + DOC_OPSINDEX };
    }
    return { pass: true, detail: 'Version History row citing INT-04 present in ' + DOC_OPSINDEX };
  }
});

// === V-152-FILENAMEMAP: all eleven registry identifiers present (not optional -- twin regression) ===
checks.push({
  id: 'FILENAMEMAP',
  name: 'V-152-FILENAMEMAP: all eleven registry identifiers (RE-226..RE-236) present in ' + DOC_FILENAMEMAP,
  run() {
    const c = readFile(DOC_FILENAMEMAP);
    if (c === null) return { pass: false, detail: DOC_FILENAMEMAP + ' missing' };
    const missing = REGISTRY_IDS.filter((id) => !c.includes(id));
    if (missing.length > 0) {
      return { pass: false, detail: 'FILENAMEMAP needle(s) absent from ' + DOC_FILENAMEMAP + ': ' + missing.join(', ') };
    }
    return { pass: true, detail: 'all eleven registry identifiers (RE-226..RE-236) present in ' + DOC_FILENAMEMAP };
  }
});

// === V-152-HUBSNOTWIRED: negative needle, justified by the RATIFIED hub-unwiring invariant (INT-05) ===
checks.push({
  id: 'HUBSNOTWIRED',
  name: 'V-152-HUBSNOTWIRED: ' + HUB_FILES.join(', ') + ' do NOT contain "recipes/05-" (ratified hub-unwiring invariant, INT-05)',
  run() {
    const hits = [];
    for (const hub of HUB_FILES) {
      const c = readFile(hub);
      if (c === null) continue; // graceful skip: hub file absent is out of this check's scope
      if (c.includes('recipes/05-')) hits.push(hub);
    }
    if (hits.length > 0) {
      return { pass: false, detail: 'HUBSNOTWIRED regression: recipes/05- referenced in ' + hits.join(', ') + ' -- the ratified hub-unwiring invariant (INT-05) is violated, not merely a file-count coincidence' };
    }
    return { pass: true, detail: 'common-issues.md / quick-ref-l1.md / quick-ref-l2.md confirmed NOT wired to recipes/05- (ratified hub-unwiring invariant, INT-05 -- durable by invariant, not by the small file count)' };
  }
});

// === V-152-SELF: the spec's guard AS WRITTEN -- own-path presence PLUS dual chain invariant ===
// See the "CORRECTION OF RECORD ON THE SPEC'S TWIN CLAIM" header note (D-30): the twin
// (check-phase-132.mjs V-132-SELF) carries ONLY the dual invariant below; it does NOT assert its
// own file's presence at its own path. This spec explicitly requires both parts, and both are
// implemented here per the transcribe-verbatim rule (D-29).
checks.push({
  id: 'SELF',
  name: 'V-152-SELF: own file present at ' + SELF_PATH + ' AND CHAIN_PHASES does NOT include 152 AND CHAIN_SKIP is empty Set',
  run() {
    if (!existsSync(join(process.cwd(), SELF_PATH))) {
      return { pass: false, detail: 'SELF regression: own file not present at ' + SELF_PATH + ' -- renamed or moved leaf' };
    }
    if (CHAIN_PHASES.includes(152)) {
      return { pass: false, detail: 'CHAIN_PHASES includes 152 -- self-reference regression' };
    }
    if (CHAIN_SKIP.size !== 0) {
      const skipList = [...CHAIN_SKIP].join(',');
      return { pass: false, detail: 'CHAIN_SKIP non-empty (' + skipList + ') -- Phase 68 7b635ca empty-Set invariant violated' };
    }
    return { pass: true, detail: 'own file present at ' + SELF_PATH + '; CHAIN_PHASES = [] (152 absent); CHAIN_SKIP = [] (Phase 68 7b635ca invariant)' };
  }
});

// === Runner loop (verbatim pattern from check-phase-126.mjs / check-phase-132.mjs) ===
const LABEL_WIDTH = 60;
function padLabel(s) {
  if (s.length >= LABEL_WIDTH) return s + ' ';
  return s + ' ' + '.'.repeat(LABEL_WIDTH - s.length) + ' ';
}

let passed = 0, failed = 0, skipped = 0;
console.log('check-phase-152 -- Phase 152 deliverables (Integration, Registry & Navigation-Last Close)\n');
for (const check of checks) {
  let result;
  try { result = check.run(); } catch (e) { result = { pass: false, detail: 'Unexpected error: ' + e.message }; }
  const prefix = '[' + check.id + '/' + checks.length + '] ' + check.name;
  const showDetail = result.detail && (VERBOSE || !result.pass || result.skipped);
  if (result.skipped) {
    skipped++;
    process.stdout.write(padLabel(prefix) + 'SKIPPED' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else if (result.pass) {
    passed++;
    process.stdout.write(padLabel(prefix) + 'PASS' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else {
    failed++;
    process.stdout.write(padLabel(prefix) + 'FAIL -- ' + result.detail + '\n');
  }
}

process.stdout.write('\nResult: ' + passed + ' PASS, ' + failed + ' FAIL, ' + skipped + ' SKIPPED\n');
process.exit(failed > 0 ? 1 : 0);
