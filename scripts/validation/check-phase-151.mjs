import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

const argv = process.argv.slice(2);
const VERBOSE = argv.includes('--verbose');

function readFile(relPath) {
  const abs = join(process.cwd(), relPath);
  if (!existsSync(abs)) return null;
  return readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
}

// Prose needles can legitimately wrap across a markdown soft line break; flatten whitespace runs to
// a single space before substring matching so a needle is not defeated by where the author wrapped.
function flat(c) {
  return c.replace(/\s+/g, ' ');
}

// Lightweight: NO chain (chain lives only in apex check-phase-153.mjs).
const CHAIN_PHASES = [];
const CHAIN_SKIP = new Set([]);

const DOC_RECIPE   = 'docs/recipes/05-enterprise-update-plan.md';
const DOC_TEMPLATE = 'docs/_templates/recipe-template.md';
const DOC_DEFERRED = '.planning/milestones/v1.19-DEFERRED-CLEANUP.md';

const checks = [];

function presence(id, path, req) {
  checks.push({
    id,
    name: 'V-151-' + id + ': ' + path + ' exists and is non-empty' + (req ? ' (' + req + ')' : ''),
    run() {
      const c = readFile(path);
      if (c === null) return { pass: false, detail: path + ' missing' };
      if (c.trim().length === 0) return { pass: false, detail: path + ' is empty' };
      return { pass: true, detail: path + ' present (' + c.length + ' bytes)' };
    }
  });
}

presence('PRESENCE', DOC_RECIPE, 'RE-227 -- corpus\'s first fleet-wide configuration artifact');

// Measured at authoring time: `**Applies to:** ...` opens every decision-point marker line, one
// per Step. `grep -c '\*\*Applies to:\*\*' docs/recipes/05-enterprise-update-plan.md` = 9.
const APPLIES_TO_RE = /^\*\*Applies to:\*\*\s*([^·\n]+?)\s*·\s*\*\*Reversibility:\*\*\s*([^\n]+)$/gm;

function markerLines(content) {
  const lines = [];
  let m;
  const re = new RegExp(APPLIES_TO_RE);
  while ((m = re.exec(content)) !== null) {
    lines.push({ platform: m[1].trim(), reversibility: m[2].trim() });
  }
  return lines;
}

// === V-151-DECISIONPOINTS: nine rated decision points, two most severe ratings present ===
checks.push({
  id: 'DECISIONPOINTS',
  name: 'V-151-DECISIONPOINTS: nine rated decision points with Destructive + Effectively irreversible present in ' + DOC_RECIPE,
  run() {
    const c = readFile(DOC_RECIPE);
    if (c === null) return { pass: false, detail: DOC_RECIPE + ' missing' };
    const lines = markerLines(c);
    if (lines.length !== 9) {
      return { pass: false, detail: 'DECISIONPOINTS regression: decision-point marker count is ' + lines.length + ', expected 9 (measured from the document itself)' };
    }
    const destructiveCount = lines.filter((l) => l.reversibility === 'Destructive').length;
    const irreversibleCount = lines.filter((l) => l.reversibility === 'Effectively irreversible').length;
    if (destructiveCount !== 1) {
      return { pass: false, detail: 'DECISIONPOINTS needle absent: exactly one "Destructive" rating expected, found ' + destructiveCount };
    }
    if (irreversibleCount !== 1) {
      return { pass: false, detail: 'DECISIONPOINTS needle absent: exactly one "Effectively irreversible" rating expected, found ' + irreversibleCount };
    }
    return { pass: true, detail: 'nine decision-point markers counted from the document; the two most severe ratings (Destructive x1, Effectively irreversible x1) both present' };
  }
});

// === V-151-APPLICABILITY: marker present for every decision point; Windows-only count meets the ratified floor ===
checks.push({
  id: 'APPLICABILITY',
  name: 'V-151-APPLICABILITY: platform-applicability marker on every decision point, Windows-only count >= ratified floor of 3 (RCP-03) in ' + DOC_RECIPE,
  run() {
    const c = readFile(DOC_RECIPE);
    if (c === null) return { pass: false, detail: DOC_RECIPE + ' missing' };
    const lines = markerLines(c);
    if (lines.length !== 9) {
      return { pass: false, detail: 'APPLICABILITY precondition absent: decision-point marker count is ' + lines.length + ', expected 9' };
    }
    const windowsOnlyCount = lines.filter((l) => l.platform === 'Windows-only').length;
    if (windowsOnlyCount < 3) {
      return { pass: false, detail: 'APPLICABILITY regression: Windows-only marker count (' + windowsOnlyCount + ') below the ratified RCP-03 floor of 3' };
    }
    return { pass: true, detail: 'all nine decision points carry a platform-applicability marker; Windows-only count (' + windowsOnlyCount + ') meets the ratified floor of 3' };
  }
});

// === V-151-ROLLBACK: "## Rollback/Recovery" present, true-count opening intact, default-channel absence present ===
function rollbackResult(content) {
  if (content === null) return { pass: false, detail: DOC_RECIPE + ' missing' };
  if (!content.includes('## Rollback/Recovery')) {
    return { pass: false, detail: 'ROLLBACK needle absent: "## Rollback/Recovery" heading not found in ' + DOC_RECIPE };
  }
  const f = flat(content);
  const required = [
    ['Four of the nine mechanisms below have no rollback path at all', 'true-count opening sentence'],
    ['Current Channel is the default for Microsoft 365 Apps for enterprise', 'default-channel identification'],
    ['reads **Not applicable** for Current Channel', 'default-channel documented no-rollback absence'],
  ];
  const missing = required.filter(([needle]) => !f.includes(needle));
  if (missing.length > 0) {
    return { pass: false, detail: 'ROLLBACK needle(s) absent from ' + DOC_RECIPE + ': ' + missing.map(([, label]) => label).join(', ') };
  }
  return { pass: true, detail: '"## Rollback/Recovery" present with its true-count opening and the default M365 channel\'s documented no-rollback absence intact' };
}
checks.push({
  id: 'ROLLBACK',
  name: 'V-151-ROLLBACK: "## Rollback/Recovery" present with true-count opening and default-channel absence in ' + DOC_RECIPE,
  run() {
    return rollbackResult(readFile(DOC_RECIPE));
  }
});

// === V-151-CONFIGARTIFACT: the recipe's own tenant-wide-configuration-plan self-description ===
checks.push({
  id: 'CONFIGARTIFACT',
  name: 'V-151-CONFIGARTIFACT: tenant-wide-configuration-plan self-description present in ' + DOC_RECIPE,
  run() {
    const c = readFile(DOC_RECIPE);
    if (c === null) return { pass: false, detail: DOC_RECIPE + ' missing' };
    const f = flat(c);
    if (!f.includes('A tenant-wide configuration plan, not a per-platform procedure guide')) {
      return { pass: false, detail: 'CONFIGARTIFACT needle absent: Scope self-description not found in ' + DOC_RECIPE };
    }
    return { pass: true, detail: 'the recipe\'s own Scope banner asserts itself as a tenant-wide configuration plan, shipped' };
  }
});

// === V-151-TEMPLATEDIVERGENCE: template promotion + deferred-cleanup ledger closure ===
checks.push({
  id: 'TEMPLATEDIVERGENCE',
  name: 'V-151-TEMPLATEDIVERGENCE: "## Rollback/Recovery" promoted into ' + DOC_TEMPLATE + ' and v1.19 deferred-cleanup ledger entry recorded CLOSED',
  run() {
    const t = readFile(DOC_TEMPLATE);
    if (t === null) return { pass: false, detail: DOC_TEMPLATE + ' missing' };
    const idxVerify = t.indexOf('## Verification');
    const idxRollback = t.indexOf('## Rollback/Recovery');
    const idxFailures = t.indexOf('## Configuration-Caused Failures');
    if (idxVerify === -1 || idxRollback === -1 || idxFailures === -1) {
      return { pass: false, detail: 'TEMPLATEDIVERGENCE needle absent: one or more of "## Verification" / "## Rollback/Recovery" / "## Configuration-Caused Failures" not found in ' + DOC_TEMPLATE };
    }
    if (!(idxVerify < idxRollback && idxRollback < idxFailures)) {
      return { pass: false, detail: 'TEMPLATEDIVERGENCE regression: "## Rollback/Recovery" is not positioned strictly between Verification and Configuration-Caused Failures in ' + DOC_TEMPLATE };
    }
    const d = readFile(DOC_DEFERRED);
    if (d === null) return { pass: false, detail: DOC_DEFERRED + ' missing' };
    const ledgerIdx = d.indexOf('ROLLBACK-RECOVERY-DIVERGENCE-COUNT');
    if (ledgerIdx === -1) {
      return { pass: false, detail: 'TEMPLATEDIVERGENCE needle absent: ROLLBACK-RECOVERY-DIVERGENCE-COUNT ledger entry not found in ' + DOC_DEFERRED };
    }
    const nextHeadingIdx = d.indexOf('\n## ', ledgerIdx + 1);
    const ledgerRegion = nextHeadingIdx === -1 ? d.slice(ledgerIdx) : d.slice(ledgerIdx, nextHeadingIdx);
    if (!ledgerRegion.includes('CLOSED by v1.21 Phase 151')) {
      return { pass: false, detail: 'TEMPLATEDIVERGENCE regression: ROLLBACK-RECOVERY-DIVERGENCE-COUNT entry in ' + DOC_DEFERRED + ' does not read CLOSED by v1.21 Phase 151' };
    }
    return { pass: true, detail: '"## Rollback/Recovery" promoted into the shared template between Verification and Configuration-Caused Failures; v1.19 deferred-cleanup ledger entry recorded CLOSED by v1.21 Phase 151' };
  }
});

// === V-151-SELF: dual-invariant guard (CHAIN_PHASES excludes 151; CHAIN_SKIP empty) ===
checks.push({
  id: 'SELF',
  name: 'V-151-SELF: CHAIN_PHASES does NOT include 151; CHAIN_SKIP is empty Set',
  run() {
    if (CHAIN_PHASES.includes(151)) {
      return { pass: false, detail: 'CHAIN_PHASES includes 151 -- self-reference regression' };
    }
    if (CHAIN_SKIP.size !== 0) {
      const skipList = [...CHAIN_SKIP].join(',');
      return { pass: false, detail: 'CHAIN_SKIP non-empty (' + skipList + ') -- Phase 68 7b635ca empty-Set invariant violated' };
    }
    return { pass: true, detail: 'CHAIN_PHASES = [] (lightweight leaf, apex is check-phase-153.mjs); CHAIN_SKIP = [] (Phase 68 7b635ca invariant)' };
  }
});

// === Runner loop (verbatim pattern from check-phase-126.mjs / check-phase-150.mjs) ===
const LABEL_WIDTH = 60;
function padLabel(s) {
  if (s.length >= LABEL_WIDTH) return s + ' ';
  return s + ' ' + '.'.repeat(LABEL_WIDTH - s.length) + ' ';
}

let passed = 0, failed = 0, skipped = 0;
console.log('check-phase-151 -- Phase 151 deliverables (Recipe #5 -- The Enterprise Update Plan)\n');
for (const check of checks) {
  let result;
  try { result = check.run(); } catch (e) { result = { pass: false, detail: 'Unexpected error: ' + e.message }; }
  const prefix = '[' + check.id + '/' + checks.length + '] ' + check.name;
  const showDetail = result.detail && (VERBOSE || !result.pass || result.skipped);
  if (result.skipped) {
    skipped++;
    process.stdout.write(padLabel(prefix) + 'SKIPPED' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else if (result.pass) {
    passed++;
    process.stdout.write(padLabel(prefix) + 'PASS' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else {
    failed++;
    process.stdout.write(padLabel(prefix) + 'FAIL -- ' + result.detail + '\n');
  }
}

process.stdout.write('\nResult: ' + passed + ' PASS, ' + failed + ' FAIL, ' + skipped + ' SKIPPED\n');
process.exit(failed > 0 ? 1 : 0);
