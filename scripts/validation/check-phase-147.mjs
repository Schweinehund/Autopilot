import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

const argv = process.argv.slice(2);
const VERBOSE = argv.includes('--verbose');

function readFile(relPath) {
  const abs = join(process.cwd(), relPath);
  if (!existsSync(abs)) return null;
  return readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
}

// Prose needles can legitimately wrap across a markdown soft line break; flatten whitespace runs to
// a single space before substring matching so a needle is not defeated by where the author wrapped.
function flat(c) {
  return c.replace(/\s+/g, ' ');
}

// Lightweight: NO chain (chain lives only in apex check-phase-153.mjs).
const CHAIN_PHASES = [];
const CHAIN_SKIP = new Set([]);

const DOC_LINUX_GUIDE = 'docs/operations/patch-management/05-linux-update-delivery.md';
const DOC_OVERVIEW    = 'docs/operations/patch-management/00-overview.md';

const checks = [];

function presence(id, path, req) {
  checks.push({
    id,
    name: 'V-147-' + id + ': ' + path + ' exists and is non-empty' + (req ? ' (' + req + ')' : ''),
    run() {
      const c = readFile(path);
      if (c === null) return { pass: false, detail: path + ' missing' };
      if (c.trim().length === 0) return { pass: false, detail: path + ' is empty' };
      return { pass: true, detail: path + ' present (' + c.length + ' bytes)' };
    }
  });
}

presence('PRESENCE', DOC_LINUX_GUIDE, 'SC#1 Linux update delivery guide');

// === V-147-ABSENCE: no native Intune Linux update policy (SC#1) ===
checks.push({
  id: 'ABSENCE',
  name: 'V-147-ABSENCE: "the policy surface does not exist" absence statement present in ' + DOC_LINUX_GUIDE,
  run() {
    const c = readFile(DOC_LINUX_GUIDE);
    if (c === null) return { pass: false, detail: DOC_LINUX_GUIDE + ' missing' };
    const f = flat(c);
    if (!f.includes('There is no native Intune Linux update policy')) {
      return { pass: false, detail: 'ABSENCE needle absent: "There is no native Intune Linux update policy" not found' };
    }
    if (!f.includes('the policy surface does not exist')) {
      return { pass: false, detail: 'ABSENCE needle absent: "the policy surface does not exist" not found' };
    }
    return { pass: true, detail: 'no-native-Linux-update-policy absence statement present in ' + DOC_LINUX_GUIDE };
  }
});

// === V-147-ROOTHAZARD: heading + three conjuncts + arithmetic (SC#2) ===
checks.push({
  id: 'ROOTHAZARD',
  name: 'V-147-ROOTHAZARD: root-context hazard heading, three conjuncts and arithmetic present in ' + DOC_LINUX_GUIDE,
  run() {
    const c = readFile(DOC_LINUX_GUIDE);
    if (c === null) return { pass: false, detail: DOC_LINUX_GUIDE + ' missing' };
    const f = flat(c);
    const required = [
      ['Root-context execution hazard.', 'hazard heading'],
      ['Every 15 minutes', 'execution-frequency conjunct'],
      ['no documented run-time cap on that surface', 'no-run-time-cap conjunct'],
      ['96 runs', 'arithmetic consequence (96 runs)'],
      ['1,440 minutes', 'arithmetic basis (1,440 minutes)'],
    ];
    const missing = required.filter(([needle]) => !f.includes(needle));
    if (missing.length > 0) {
      return { pass: false, detail: 'ROOTHAZARD needle(s) absent: ' + missing.map(([, label]) => label).join(', ') };
    }
    return { pass: true, detail: 'hazard heading, three conjuncts and the 96-runs/1,440-minutes arithmetic all present in ' + DOC_LINUX_GUIDE };
  }
});

// === V-147-ORIGINS: four enabled origins + reboot-required marker detection (SC#3) ===
checks.push({
  id: 'ORIGINS',
  name: 'V-147-ORIGINS: four-enabled-origins statement + reboot-required marker detection present in ' + DOC_LINUX_GUIDE,
  run() {
    const c = readFile(DOC_LINUX_GUIDE);
    if (c === null) return { pass: false, detail: DOC_LINUX_GUIDE + ' missing' };
    const f = flat(c);
    const required = [
      ['Four origins are enabled by default, not one.', 'four-origins statement'],
      ['## Reboot Handling', 'reboot handling H2'],
      ['if the file `/run/reboot-required` exists, then you will need to reboot', 'reboot-required marker quote'],
    ];
    const missing = required.filter(([needle]) => !f.includes(needle));
    if (missing.length > 0) {
      return { pass: false, detail: 'ORIGINS needle(s) absent: ' + missing.map(([, label]) => label).join(', ') };
    }
    return { pass: true, detail: 'four-enabled-origins statement and reboot-required marker detection present in ' + DOC_LINUX_GUIDE };
  }
});

// === V-147-ENTITLEMENT: Ubuntu Pro/Livepatch as a Canonical-side entitlement (SC#4) ===
checks.push({
  id: 'ENTITLEMENT',
  name: 'V-147-ENTITLEMENT: Canonical-side subscription entitlement framing present in ' + DOC_LINUX_GUIDE,
  run() {
    const c = readFile(DOC_LINUX_GUIDE);
    if (c === null) return { pass: false, detail: DOC_LINUX_GUIDE + ' missing' };
    const f = flat(c);
    if (!f.includes('Both are Canonical-side subscription entitlements that sit entirely outside Intune')) {
      return { pass: false, detail: 'ENTITLEMENT needle absent: Canonical-side subscription entitlement sentence not found' };
    }
    return { pass: true, detail: 'Ubuntu Pro / Livepatch presented as a Canonical-side subscription entitlement, not an Intune feature, in ' + DOC_LINUX_GUIDE };
  }
});

// === V-147-OVERVIEWCOLUMN: appended Linux column + unchanged frontmatter platform value ===
checks.push({
  id: 'OVERVIEWCOLUMN',
  name: 'V-147-OVERVIEWCOLUMN: appended Linux column present, frontmatter platform value unchanged in ' + DOC_OVERVIEW,
  run() {
    const c = readFile(DOC_OVERVIEW);
    if (c === null) return { pass: false, detail: DOC_OVERVIEW + ' missing' };
    if (!/\|\s*Concept\s*\|.*\|\s*Linux\s*\|/.test(c)) {
      return { pass: false, detail: 'OVERVIEWCOLUMN needle absent: appended Linux column header not found' };
    }
    // Positive assertion on the ratified value (D-70 style), not a negative on the platform name.
    if (!/^platform:\s*cross-platform\s*$/m.test(c)) {
      return { pass: false, detail: 'OVERVIEWCOLUMN regression: frontmatter platform value is not the ratified "cross-platform"' };
    }
    return { pass: true, detail: 'six-column table with appended Linux header present; frontmatter platform: cross-platform unchanged' };
  }
});

// === V-147-MISATTRIBUTION: the five-minute cap is scoped OFF the root-context hazard bullet region ===
// Intra-file scoping (not a corpus-wide negative): the interval is legitimately documented on its own
// surface -- the discovery-script section of this SAME guide -- so a corpus-wide ban would be wrong.
checks.push({
  id: 'MISATTRIBUTION',
  name: 'V-147-MISATTRIBUTION: "five minutes" absent from the root-context hazard bullet region, present on its own surface in ' + DOC_LINUX_GUIDE,
  run() {
    const c = readFile(DOC_LINUX_GUIDE);
    if (c === null) return { pass: false, detail: DOC_LINUX_GUIDE + ' missing' };
    const hazardStart = c.indexOf('**Root-context execution hazard.**');
    if (hazardStart === -1) return { pass: false, detail: 'MISATTRIBUTION precondition absent: hazard heading not found (see ROOTHAZARD)' };
    const nextBoldAfter = c.indexOf('**Set an explicit, justified execution frequency', hazardStart);
    const hazardEnd = nextBoldAfter === -1 ? c.length : nextBoldAfter;
    const hazardRegion = c.slice(hazardStart, hazardEnd);
    if (hazardRegion.includes('five minutes')) {
      return { pass: false, detail: 'MISATTRIBUTION regression: "five minutes" leaked into the root-context hazard bullet region -- the discovery-script interval must not be attributed to the platform-script hazard' };
    }
    if (!c.includes('five minutes')) {
      return { pass: false, detail: 'MISATTRIBUTION needle absent: "five minutes" does not appear anywhere in ' + DOC_LINUX_GUIDE + ' -- the interval should be legitimately documented on its own (discovery-script) surface' };
    }
    return { pass: true, detail: '"five minutes" absent from the hazard bullet region and correctly documented on its own discovery-script surface elsewhere in ' + DOC_LINUX_GUIDE };
  }
});

// === V-147-SELF: dual-invariant guard (CHAIN_PHASES excludes 147; CHAIN_SKIP empty) ===
checks.push({
  id: 'SELF',
  name: 'V-147-SELF: CHAIN_PHASES does NOT include 147; CHAIN_SKIP is empty Set',
  run() {
    if (CHAIN_PHASES.includes(147)) {
      return { pass: false, detail: 'CHAIN_PHASES includes 147 -- self-reference regression' };
    }
    if (CHAIN_SKIP.size !== 0) {
      const skipList = [...CHAIN_SKIP].join(',');
      return { pass: false, detail: 'CHAIN_SKIP non-empty (' + skipList + ') -- Phase 68 7b635ca empty-Set invariant violated' };
    }
    return { pass: true, detail: 'CHAIN_PHASES = [] (lightweight leaf, apex is check-phase-153.mjs); CHAIN_SKIP = [] (Phase 68 7b635ca invariant)' };
  }
});

// === Runner loop (verbatim pattern from check-phase-126.mjs) ===
const LABEL_WIDTH = 60;
function padLabel(s) {
  if (s.length >= LABEL_WIDTH) return s + ' ';
  return s + ' ' + '.'.repeat(LABEL_WIDTH - s.length) + ' ';
}

let passed = 0, failed = 0, skipped = 0;
console.log('check-phase-147 -- Phase 147 deliverables (Linux Update Delivery)\n');
for (const check of checks) {
  let result;
  try { result = check.run(); } catch (e) { result = { pass: false, detail: 'Unexpected error: ' + e.message }; }
  const prefix = '[' + check.id + '/' + checks.length + '] ' + check.name;
  const showDetail = result.detail && (VERBOSE || !result.pass || result.skipped);
  if (result.skipped) {
    skipped++;
    process.stdout.write(padLabel(prefix) + 'SKIPPED' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else if (result.pass) {
    passed++;
    process.stdout.write(padLabel(prefix) + 'PASS' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else {
    failed++;
    process.stdout.write(padLabel(prefix) + 'FAIL -- ' + result.detail + '\n');
  }
}

process.stdout.write('\nResult: ' + passed + ' PASS, ' + failed + ' FAIL, ' + skipped + ' SKIPPED\n');
process.exit(failed > 0 ? 1 : 0);
