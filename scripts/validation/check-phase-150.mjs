// === V-150-RECOVERY-*: "## Recovery" heading present, each scoped to a single vendor file ===
// This is the phase's hardest constraint (every Recovery section present even where the vendor is
// silent) and exactly what a later editor deleting an "empty-looking" section would violate.
function recoveryCheck(id, path, label) {
  checks.push({
    id,
    name: 'V-150-' + id + ': "## Recovery" heading present in ' + path + ' (scoped)',
    run() {
      const c = readFile(path);
      if (c === null) return { pass: false, detail: path + ' missing' };
      if (!c.includes('## Recovery')) {
        return { pass: false, detail: 'RECOVERY-' + label + ' regression: "## Recovery" heading absent from ' + path };
      }
      return { pass: true, detail: '"## Recovery" heading present in ' + path };
    }
  });
}
recoveryCheck('RECOVERY-DELL', DOC_DELL, 'DELL');
recoveryCheck('RECOVERY-HP', DOC_HP, 'HP');
recoveryCheck('RECOVERY-LENOVO', DOC_LENOVO, 'LENOVO');

// Count bullets under a bold-lead-in enumeration, from the enumeration's own start to the next
// paragraph that is not a bullet line. Used for the matrix's countable-relationship needle.
function countBulletsAfter(content, leadIn, stopAt) {
  const start = content.indexOf(leadIn);
  if (start === -1) return null;
  const stop = content.indexOf(stopAt, start);
  if (stop === -1) return null;
  const region = content.slice(start, stop);
  const bullets = region.match(/^- /gm) || [];
  return bullets.length;
}

// === V-150-MATRIX: the matrix's own row/column structure + a countable relationship it records itself ===
// A matrix needle that duplicates a guide needle can pass while the two artifacts disagree, so this
// asserts the matrix's OWN structure and the countable relationship its own review recorded, rather
// than restating a guide claim (per the plan's explicit instruction).
checks.push({
  id: 'MATRIX',
  name: 'V-150-MATRIX: row set, shared six-H2 column structure, and the silence-cell/documentation-silences count relationship present in ' + DOC_MATRIX,
  run() {
    const c = readFile(DOC_MATRIX);
    if (c === null) return { pass: false, detail: DOC_MATRIX + ' missing' };
    const missingHeadings = CAPABILITY_HEADINGS.filter((h) => !c.includes(h));
    if (missingHeadings.length > 0) {
      return { pass: false, detail: 'MATRIX needle(s) absent: capability H2(s) missing from ' + DOC_MATRIX + ': ' + missingHeadings.join(', ') };
    }
    for (const row of ['| Dell |', '| HP |', '| Lenovo |']) {
      if (!c.includes(row)) {
        return { pass: false, detail: 'MATRIX needle absent: row "' + row + '" not found in ' + DOC_MATRIX };
      }
    }
    if (!c.includes('## Key Gaps Summary')) {
      return { pass: false, detail: 'MATRIX needle absent: "## Key Gaps Summary" heading not found in ' + DOC_MATRIX };
    }
    if (!c.includes('**Documentation silences**')) {
      return { pass: false, detail: 'MATRIX needle absent: "Documentation silences" enumeration not found in ' + DOC_MATRIX };
    }
    const tablesRegion = c.slice(0, c.indexOf('## Key Gaps Summary'));
    const silenceCellCount = (tablesRegion.match(/Not documented by vendor/g) || []).length;
    const silenceBulletCount = countBulletsAfter(c, '**Documentation silences**', 'Filing a documented silence');
    if (silenceBulletCount === null) {
      return { pass: false, detail: 'MATRIX precondition absent: could not bound the Documentation silences enumeration' };
    }
    if (silenceCellCount === 0 || silenceBulletCount === 0) {
      return { pass: false, detail: 'MATRIX regression: silence-cell count (' + silenceCellCount + ') or documentation-silences bullet count (' + silenceBulletCount + ') is zero' };
    }
    if (silenceCellCount !== silenceBulletCount) {
      return { pass: false, detail: 'MATRIX regression: table silence-cell count (' + silenceCellCount + ') no longer equals the Documentation silences enumeration (' + silenceBulletCount + ') -- matrix and its own gap list disagree' };
    }
    return { pass: true, detail: 'row set, shared six-H2 columns present; silence-cell count (' + silenceCellCount + ') matches the Documentation silences enumeration (' + silenceBulletCount + ')' };
  }
});

// === V-150-SELF: dual-invariant guard (CHAIN_PHASES excludes 150; CHAIN_SKIP empty) ===
checks.push({
  id: 'SELF',
  name: 'V-150-SELF: CHAIN_PHASES does NOT include 150; CHAIN_SKIP is empty Set',
  run() {
    if (CHAIN_PHASES.includes(150)) {
      return { pass: false, detail: 'CHAIN_PHASES includes 150 -- self-reference regression' };
    }
    if (CHAIN_SKIP.size !== 0) {
      const skipList = [...CHAIN_SKIP].join(',');
      return { pass: false, detail: 'CHAIN_SKIP non-empty (' + skipList + ') -- Phase 68 7b635ca empty-Set invariant violated' };
    }
    return { pass: true, detail: 'CHAIN_PHASES = [] (lightweight leaf, apex is check-phase-153.mjs); CHAIN_SKIP = [] (Phase 68 7b635ca invariant)' };
  }
});

// === Runner loop (verbatim pattern from check-phase-126.mjs / check-phase-147..149.mjs) ===
const LABEL_WIDTH = 60;
function padLabel(s) {
  if (s.length >= LABEL_WIDTH) return s + ' ';
  return s + ' ' + '.'.repeat(LABEL_WIDTH - s.length) + ' ';
}

let passed = 0, failed = 0, skipped = 0;
console.log('check-phase-150 -- Phase 150 deliverables (Per-OEM BIOS Guides & Capability Matrix)\n');
for (const check of checks) {
  let result;
  try { result = check.run(); } catch (e) { result = { pass: false, detail: 'Unexpected error: ' + e.message }; }
  const prefix = '[' + check.id + '/' + checks.length + '] ' + check.name;
  const showDetail = result.detail && (VERBOSE || !result.pass || result.skipped);
  if (result.skipped) {
    skipped++;
    process.stdout.write(padLabel(prefix) + 'SKIPPED' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else if (result.pass) {
    passed++;
    process.stdout.write(padLabel(prefix) + 'PASS' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else {
    failed++;
    process.stdout.write(padLabel(prefix) + 'FAIL -- ' + result.detail + '\n');
  }
}

process.stdout.write('\nResult: ' + passed + ' PASS, ' + failed + ' FAIL, ' + skipped + ' SKIPPED\n');
process.exit(failed > 0 ? 1 : 0);
