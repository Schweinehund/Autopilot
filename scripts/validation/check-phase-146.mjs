#!/usr/bin/env node
// check-phase-146.mjs -- Phase 146 deliverables (Windows Driver & Firmware Update Depth)
//
// v1.21 CONTENT leaf, templated on check-phase-126.mjs / check-phase-145.mjs (the content-leaf
// family), NOT on check-phase-141..143.mjs (the tooling-only v1.20 leaf family -- 153-CONTEXT.md
// D-22). Phase 146 shipped a dedicated driver-and-firmware guide, promoted out of the disambiguation
// stub in 01-windows-wufb-rings.md, and this leaf locks both the new guide's content AND that stub's
// retention set -- the phase's hardest constraint, per D-23's own read of the phase.
//
// DERIVATION RULE (D-27): every needle below was derived from 146-VERIFICATION.md, read by the
// author at AUTHORING TIME, and measured against the live corpus with the grep recorded in
// 153-06-SUMMARY.md. This validator itself makes ZERO reads under .planning/ at RUNTIME -- every
// path it opens is under docs/.
//
// ARITHMETIC RECONCILIATION (D-24): CHAIN_PHASES is an empty array below. HARN-04's "CHAIN_PHASES
// generated by arithmetic, never transcribed" rule binds the APEX (check-phase-153.mjs), which is the
// only file in this lineage that owns a chain. A lightweight leaf has no chain to generate, so an
// empty literal here is not a transcription and is not scored as non-compliance with that rule.
//
// GATE-RESPAWN DECISION (D-38): this leaf does NOT re-spawn C17, the link checker, or any other
// corpus gate as a subprocess. It reads file content directly. No process-spawning module is imported.
//
// Assertion classes:
//   V-146-PRESENCE          06-windows-driver-firmware-updates.md exists and is non-empty
//   V-146-RETENTION         the stub-and-move retention set on 01-windows-wufb-rings.md: the H2, the
//                           driver-firmware-policy anchor, the "This is NOT a ring" disambiguation and
//                           the dual-scan pitfall material all survive the promotion (DRV-07)
//   V-146-DEFERRALDEADLINE  the deferral/deadline asymmetry triad is stated in 06 (DRV-02)
//   V-146-ABSENCES          the three named absences ship as their own bold lead-in sentences: no
//                           rollback, no Autopilot governance, destructive Automatic->Manual switch
//   V-146-COEXIST           the ConfigMgr co-existence procedure carries its undefined-state warning
//                           (DRV-06)
//   V-146-SINGULARFORM      06 uses the singular "WUfB deployment ring" form the phase adopted to
//                           avoid tripping the plural-only C11 Autopatch-rings regex -- assert the
//                           shipped form, not the regex it was chosen to avoid
//   V-146-SELF              CHAIN_PHASES does NOT include 146 AND CHAIN_SKIP is empty Set
//
// Usage: node scripts/validation/check-phase-146.mjs [--verbose]
// Exit code: 0 if all PASS or SKIPPED; 1 if any FAIL.

import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

const argv = process.argv.slice(2);
const VERBOSE = argv.includes('--verbose');

function readFile(relPath) {
  const abs = join(process.cwd(), relPath);
  if (!existsSync(abs)) return null;
  return readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
}

// Lightweight: NO chain (chain lives only in apex check-phase-153.mjs).
const CHAIN_PHASES = [];
const CHAIN_SKIP = new Set([]);

const DOC_DRIVER_GUIDE = 'docs/operations/patch-management/06-windows-driver-firmware-updates.md';
const DOC_WIN_RINGS    = 'docs/operations/patch-management/01-windows-wufb-rings.md';

const checks = [];

function presence(id, path, req) {
  checks.push({
    id,
    name: 'V-146-' + id + ': ' + path + ' exists and is non-empty' + (req ? ' (' + req + ')' : ''),
    run() {
      const c = readFile(path);
      if (c === null) return { pass: false, detail: path + ' missing' };
      if (c.trim().length === 0) return { pass: false, detail: path + ' is empty' };
      return { pass: true, detail: path + ' present (' + c.length + ' bytes)' };
    }
  });
}

presence('PRESENCE', DOC_DRIVER_GUIDE, 'DRV-01 promoted driver and firmware guide');

// === V-146-RETENTION: the stub-and-move retention set on 01-windows-wufb-rings.md (DRV-07) ===
checks.push({
  id: 'RETENTION',
  name: 'V-146-RETENTION: promotion-retention set survives in ' + DOC_WIN_RINGS,
  run() {
    const c = readFile(DOC_WIN_RINGS);
    if (c === null) return { pass: false, detail: DOC_WIN_RINGS + ' missing' };
    const required = [
      ['<a id="driver-firmware-policy"></a>', 'retained anchor'],
      ['## Driver and Firmware Update Policy', 'retained H2'],
      ['This is NOT a ring', 'retained disambiguation statement'],
      ['Dual-scan source conflict pitfall', 'retained dual-scan material'],
      ['dual-scan', 'retained dual-scan literal'],
    ];
    const missing = required.filter(([needle]) => !c.includes(needle));
    if (missing.length > 0) {
      return { pass: false, detail: 'RETENTION needle(s) absent: ' + missing.map(([, label]) => label).join(', ') };
    }
    return { pass: true, detail: 'anchor, H2, disambiguation and dual-scan material all present in ' + DOC_WIN_RINGS };
  }
});

// === V-146-DEFERRALDEADLINE: the deferral/deadline asymmetry triad in 06 (DRV-02) ===
checks.push({
  id: 'DEFERRALDEADLINE',
  name: 'V-146-DEFERRALDEADLINE: deferral/deadline asymmetry triad present in ' + DOC_DRIVER_GUIDE,
  run() {
    const c = readFile(DOC_DRIVER_GUIDE);
    if (c === null) return { pass: false, detail: DOC_DRIVER_GUIDE + ' missing' };
    const required = [
      ['## Deferral and Deadline Behavior', 'H2'],
      ['does not apply to drivers that are approved using the Driver Update Policy', 'deferral-does-not-reach-drivers quote'],
      ['The Quality Update deadline and grace period settings apply to drivers.', 'deadline-and-grace-period-do-reach-drivers quote'],
    ];
    const missing = required.filter(([needle]) => !c.includes(needle));
    if (missing.length > 0) {
      return { pass: false, detail: 'DEFERRALDEADLINE needle(s) absent: ' + missing.map(([, label]) => label).join(', ') };
    }
    return { pass: true, detail: 'deferral/deadline asymmetry triad (H2 + both sourced quotes) present in ' + DOC_DRIVER_GUIDE };
  }
});

// === V-146-ABSENCES: the three named absences ship as bold lead-ins (SC#3) ===
checks.push({
  id: 'ABSENCES',
  name: 'V-146-ABSENCES: the three named absences present in ' + DOC_DRIVER_GUIDE,
  run() {
    const c = readFile(DOC_DRIVER_GUIDE);
    if (c === null) return { pass: false, detail: DOC_DRIVER_GUIDE + ' missing' };
    const required = [
      ['There is no driver rollback.', 'no-rollback absence'],
      ['do not apply during Windows Autopilot', 'no-Autopilot-governance absence'],
      ['Switching between Automatic and Manual mode is destructive.', 'destructive-mode-switch absence'],
    ];
    const missing = required.filter(([needle]) => !c.includes(needle));
    if (missing.length > 0) {
      return { pass: false, detail: 'ABSENCES needle(s) absent: ' + missing.map(([, label]) => label).join(', ') };
    }
    return { pass: true, detail: 'all three named absences present in ' + DOC_DRIVER_GUIDE };
  }
});

// === V-146-COEXIST: ConfigMgr co-existence procedure with its undefined-state warning (DRV-06) ===
checks.push({
  id: 'COEXIST',
  name: 'V-146-COEXIST: ConfigMgr co-existence procedure + undefined-state warning present in ' + DOC_DRIVER_GUIDE,
  run() {
    const c = readFile(DOC_DRIVER_GUIDE);
    if (c === null) return { pass: false, detail: DOC_DRIVER_GUIDE + ' missing' };
    const required = [
      ['## Configuration Manager Co-management and Co-existence', 'co-existence H2'],
      ['undefined and unpredictable device state', 'undefined-state warning'],
    ];
    const missing = required.filter(([needle]) => !c.includes(needle));
    if (missing.length > 0) {
      return { pass: false, detail: 'COEXIST needle(s) absent: ' + missing.map(([, label]) => label).join(', ') };
    }
    const h2Idx = c.indexOf('## Configuration Manager Co-management and Co-existence');
    const warnIdx = c.indexOf('undefined and unpredictable device state');
    if (warnIdx < h2Idx) {
      return { pass: false, detail: 'COEXIST ordering regression: undefined-state warning appears before its own H2' };
    }
    return { pass: true, detail: 'co-existence procedure H2 and undefined-state warning present, in order, in ' + DOC_DRIVER_GUIDE };
  }
});

// === V-146-SINGULARFORM: 06 uses the singular "WUfB deployment ring" form (C11 avoidance) ===
checks.push({
  id: 'SINGULARFORM',
  name: 'V-146-SINGULARFORM: "WUfB deployment ring" singular form present, plural absent in ' + DOC_DRIVER_GUIDE,
  run() {
    const c = readFile(DOC_DRIVER_GUIDE);
    if (c === null) return { pass: false, detail: DOC_DRIVER_GUIDE + ' missing' };
    if (!c.includes('WUfB deployment ring')) {
      return { pass: false, detail: 'SINGULARFORM needle absent: "WUfB deployment ring" not found in ' + DOC_DRIVER_GUIDE };
    }
    if (/WUfB deployment rings\b/.test(c)) {
      return { pass: false, detail: 'SINGULARFORM regression: plural "WUfB deployment rings" found in ' + DOC_DRIVER_GUIDE };
    }
    return { pass: true, detail: 'singular "WUfB deployment ring" form present, plural form absent, in ' + DOC_DRIVER_GUIDE };
  }
});

// === V-146-SELF: dual-invariant guard (CHAIN_PHASES excludes 146; CHAIN_SKIP empty) ===
checks.push({
  id: 'SELF',
  name: 'V-146-SELF: CHAIN_PHASES does NOT include 146; CHAIN_SKIP is empty Set',
  run() {
    if (CHAIN_PHASES.includes(146)) {
      return { pass: false, detail: 'CHAIN_PHASES includes 146 -- self-reference regression' };
    }
    if (CHAIN_SKIP.size !== 0) {
      const skipList = [...CHAIN_SKIP].join(',');
      return { pass: false, detail: 'CHAIN_SKIP non-empty (' + skipList + ') -- Phase 68 7b635ca empty-Set invariant violated' };
    }
    return { pass: true, detail: 'CHAIN_PHASES = [] (lightweight leaf, apex is check-phase-153.mjs); CHAIN_SKIP = [] (Phase 68 7b635ca invariant)' };
  }
});

// === Runner loop (verbatim pattern from check-phase-126.mjs) ===
const LABEL_WIDTH = 60;
function padLabel(s) {
  if (s.length >= LABEL_WIDTH) return s + ' ';
  return s + ' ' + '.'.repeat(LABEL_WIDTH - s.length) + ' ';
}

let passed = 0, failed = 0, skipped = 0;
console.log('check-phase-146 -- Phase 146 deliverables (Windows Driver & Firmware Update Depth)\n');
for (const check of checks) {
  let result;
  try { result = check.run(); } catch (e) { result = { pass: false, detail: 'Unexpected error: ' + e.message }; }
  const prefix = '[' + check.id + '/' + checks.length + '] ' + check.name;
  const showDetail = result.detail && (VERBOSE || !result.pass || result.skipped);
  if (result.skipped) {
    skipped++;
    process.stdout.write(padLabel(prefix) + 'SKIPPED' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else if (result.pass) {
    passed++;
    process.stdout.write(padLabel(prefix) + 'PASS' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else {
    failed++;
    process.stdout.write(padLabel(prefix) + 'FAIL -- ' + result.detail + '\n');
  }
}

process.stdout.write('\nResult: ' + passed + ' PASS, ' + failed + ' FAIL, ' + skipped + ' SKIPPED\n');
process.exit(failed > 0 ? 1 : 0);
