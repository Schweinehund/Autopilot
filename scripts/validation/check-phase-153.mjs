// Chain-apex of v1.21 -- HARN-04. Ships the v1.21 chain-apex validator: a 105-entry chain spanning
// every integer 48 through 152, HARNESS repointed to v1.21-milestone-audit.mjs. Structural template
// only from check-phase-144.mjs (AUDIT + CHAIN + AUDIT-HARNESS + SELF) -- the chain array and its
// module-load guards are INDEPENDENTLY RE-DERIVED here, never transcribed forward. The three HAZARD
// FIXes present in check-phase-144.mjs are INHERITED as MECHANISM, not re-invented, but every count
// and span string they emit is re-derived at authoring time -- see below. This apex additionally
// carries ONE check beyond the predecessor's five categories (added by Task 2 of this plan): the
// frozen carve-out successor (C17CARVEOUT-SUCCESSOR, D-20), because Phase 153 is this phase's own
// successor validator and a standalone file for one check would be a sixteenth validator nobody runs.
// Source of truth: .planning/phases/153-harness-close-v120-pin-c17-frozen-aware-residue-19th-path-a/153-CONTEXT.md
//   and .planning/phases/153-harness-close-v120-pin-c17-frozen-aware-residue-19th-path-a/153-PATTERNS.md
//
// CRITICAL -- [48..N-1] invariant: the chain array spans 48..152 (NOT 48..153, which would include
// phase 153 itself, tripping V-153-SELF self-reference FAIL; NOT a truncated range, which would fail
// the length!==105 / terminus!==152 throws). 152 minus 48 plus 1 = 105 entries, GENERATED by
// arithmetic (Array.from), never hand-transcribed. Contiguity on disk was confirmed at authoring time:
// every integer 48..152 has a corresponding scripts/validation/check-phase-{N}.mjs file (the only
// gaps ever present in this span were the eight leaf numbers 145..152, all authored by 153-05..153-08
// ahead of this apex, per the precondition below).
//
// CRITICAL -- CHAIN_SKIP invariant: CHAIN_SKIP = new Set([]) -- NEVER add entries.
// V-153-SELF hard-asserts CHAIN_SKIP.size === 0 per Phase 68 7b635ca invariant, carried forward
// unchanged into v1.21.
//
// CRITICAL -- CHAIN_EXTRA disjointness guard: CHAIN_EXTRA = [30, 31] carries forward VERBATIM, stays
// outside all three CHAIN_PHASES module-load guards (dedup/length/termini) and outside V-153-SELF's
// dual-invariant, exactly as check-phase-144.mjs keeps it. But CHAIN_EXTRA is declared AFTER those
// three guards, so it is structurally uncoverable by them -- a sidecar member silently absorbed into
// CHAIN_PHASES (or vice versa) would pass all three. This file carries the fourth guard forward:
// assert at module load that every CHAIN_EXTRA member is absent from CHAIN_PHASES. Collapsing
// CHAIN_EXTRA into the span is forbidden.
//
// CRITICAL -- ordering: the AUDIT-HARNESS step's existence-absent branch is a hard FAIL and sits
// BEFORE the NESTED guard (added by Task 2), so an ordering slip becomes a recorded FAIL, not a
// silently skipped regression. Ordering is harness, then leaves, then apex -- an apex run before the
// harness exists emits a failure indistinguishable from a real regression.
//
// HAZARD FIX 1 (inherited mechanism) -- explicit maxBuffer on execFileSync: sets
// maxBuffer: 20 * 1024 * 1024 (20 MiB) -- generous headroom for the most verbose single child (the
// AUDIT-HARNESS step running the 16-check v1.21-milestone-audit.mjs --verbose, counted directly off
// the live checks array at authoring time, not copied from any predecessor's stale count) without
// masking a genuinely runaway process. Applied at BOTH spawn sites -- the chain spawn (this task) and
// the harness spawn (Task 2) -- because the default overflows into a throw that is not a
// missing-executable throw and therefore becomes a FAIL.
//
// HAZARD FIX 2 (inherited mechanism) -- narrowed missing-child classifier: restricts classification
// to the two unambiguous OS-level signals -- ENOENT (file not found) and shell exit status 127
// (command not found). Everything else -- including a module-load throw from one of THIS file's own
// dedup/length/termini/disjointness guards firing inside a child process -- falls through to FAIL,
// rather than being converted into a green SKIP by a loose two-substring stderr heuristic (testing
// English fragments of the shape "not found" / a resolution-failure phrase) carried by
// check-phase-141.mjs:80, check-phase-142.mjs:82 and check-phase-143.mjs:96,121,146. That loose form
// is NEVER used here.
//
// HAZARD FIX 3 (inherited mechanism) -- non-existent chain child is a FAIL, not a skip: CHAIN_PHASES
// is a fixed, asserted 105-entry span; a member of it missing from disk is a regression (a deleted
// predecessor validator), not a benign gap. This is why leaves 145-152 MUST be authored before this
// apex -- apex-first would emit eight FAILs indistinguishable from a real regression.
//
// Assertion classes:
//   V-153-AUDIT                153-VERIFICATION.md heading-presence (added Task 2)
//   V-153-CHAIN-{48..152}      105 subprocesses; each check-phase-{N}.mjs exits 0 (NESTED-aware)
//   V-153-CHAIN-{30,31}        2 sidecar subprocesses (CHAIN_EXTRA), same shape, disjoint from the span
//   V-153-AUDIT-HARNESS        scripts/validation/v1.21-milestone-audit.mjs exits 0 (added Task 2)
//   V-153-C17CARVEOUT-SUCCESSOR  corrects check-phase-140.mjs's now-false C17CARVEOUT prose (added Task 2)
//   V-153-SELF                 CHAIN_PHASES does NOT include 153 AND CHAIN_SKIP is empty Set
//                               (dual-invariant)
//
// Executed children (this task's chain loop): 107 (105 CHAIN_PHASES + 2 CHAIN_EXTRA). Full apex total
// checks once Task 2 lands: 111 (1 AUDIT + 107 chain + 1 AUDIT-HARNESS + 1 C17CARVEOUT-SUCCESSOR +
// 1 SELF). Formula: 1 + 105 + 2 + 1 + 1 + 1 = 111.
// Expected result triples for the FULL apex (post-Task-2), exact:
//   111 PASS, 0 FAIL, 0 SKIPPED   -- once 153-VERIFICATION.md exists
//   110 PASS, 0 FAIL, 1 SKIPPED   -- while 153-VERIFICATION.md does not yet exist (AUDIT SKIP-PASSES)
//   109 PASS, 1 FAIL, 1 SKIPPED   -- if run before v1.21-milestone-audit.mjs exists (AUDIT-HARNESS
//                                     FAILs, its existence branch precedes the NESTED guard)
// This apex sets CHECK_PHASE_NESTED=1 on every child it spawns -- it structurally cannot produce, and
// must never be described as producing, an admissible result across a NESTED invocation. A nested run
// of this apex returns a small number of passes, zero failures and a large number of skips at exit 0
// -- a result that reads as a pass and is NOT one. Close evidence is never captured from a nested run.
//
// Timeout budgets (inherited mechanism): 600s per-peer (phaseNum >= 67) / 300s per-subprocess, and the
// AUDIT-HARNESS 300s timeout. This apex is NEVER added to its own CHAIN_PHASES -- that is the exact
// self-reference V-153-SELF hard-fails on.
//
// Lineage: structural template check-phase-144.mjs (v1.20's apex); chain span, guards and every
// runtime-emitted literal independently re-derived this phase.
//
// Run the apex chain SEPARATELY from any verifier or prose-guard pass -- a link/anchor edit is a
// prose change and has tripped banned-phrase guards after a passed verifier before.
//
// Usage: node scripts/validation/check-phase-153.mjs [--verbose]
// Exit code: 0 if all PASS or SKIPPED; 1 if any FAIL.

import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import process from 'node:process';
import { execFailDetail } from './_lib/exec-fail-detail.mjs';

const argv = process.argv.slice(2);
const VERBOSE = argv.includes('--verbose');

function readFile(relPath) {
  const abs = join(process.cwd(), relPath);
  if (!existsSync(abs)) return null;
  return readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
}

const HARNESS = 'scripts/validation/v1.21-milestone-audit.mjs';

// HAZARD FIX 1: explicit maxBuffer (20 MiB) -- see header comment for the chosen-value rationale.
// Applied at BOTH spawn sites (chain spawn below; harness spawn added in Task 2).
const SUBPROCESS_MAX_BUFFER = 20 * 1024 * 1024;

// Phase 153 chain-apex spans every integer 48..152 (152 - 48 + 1 = 105 entries).
// GENERATED by arithmetic, not hand-transcribed.
const CHAIN_START = 48;
const CHAIN_END = 152; // [48..N-1] invariant for N=153: apex EXCLUDES its own phase (153).
const CHAIN_PHASES = Array.from({ length: CHAIN_END - CHAIN_START + 1 }, (_, i) => CHAIN_START + i);

// CHAIN_SKIP topology: empty per Phase 68 7b635ca invariant -- no entries to suppress.
// NEVER add entries: V-153-SELF hard-asserts CHAIN_SKIP.size === 0.
const CHAIN_SKIP = new Set([]);

// De-duplication guard: length + termini asserts alone do not catch a duplicated/dropped interior
// entry. Assert the set of unique values also has exactly 105 members.
if (new Set(CHAIN_PHASES).size !== CHAIN_PHASES.length) {
  throw new Error('check-phase-153 CHAIN_PHASES contains duplicate entries (unique count ' + new Set(CHAIN_PHASES).size + ' !== ' + CHAIN_PHASES.length + ')');
}

// Programmatic bound assertions (fail-loud at module load if the chain topology drifts):
// CHAIN_PHASES must be exactly 105 entries and terminate at 152 (the [48..N-1] invariant for N=153).
if (CHAIN_PHASES.length !== 105) {
  throw new Error('check-phase-153 CHAIN_PHASES length ' + CHAIN_PHASES.length + ' !== 105 (integers 48..152 inclusive)');
}
if (CHAIN_PHASES[0] !== 48 || CHAIN_PHASES[CHAIN_PHASES.length - 1] !== 152) {
  throw new Error('check-phase-153 CHAIN_PHASES must span 48..152 (got ' + CHAIN_PHASES[0] + '..' + CHAIN_PHASES[CHAIN_PHASES.length - 1] + ')');
}

const checks = [];

// CHAIN_EXTRA: carried forward verbatim from check-phase-144.mjs -- NOT part of the arithmetic
// CHAIN_PHASES span and NOT subject to its three module-load guards (dedup/length/termini) above, nor
// to V-153-SELF's two invariants below -- both stay scoped to CHAIN_PHASES/CHAIN_SKIP only.
const CHAIN_EXTRA = [30, 31];

// Guard 153 carries forward from 144: CHAIN_EXTRA is declared AFTER all three CHAIN_PHASES guards
// above, so a sidecar member silently absorbed into (or overlapping) the span would pass all three
// undetected. Assert disjointness explicitly, at module load.
if (!CHAIN_EXTRA.every((n) => !CHAIN_PHASES.includes(n))) {
  throw new Error('check-phase-153 CHAIN_EXTRA overlaps CHAIN_PHASES -- must stay disjoint');
}

// === V-153-CHAIN-NN: chain regression-guards for check-phase-{48..152}.mjs plus the {30,31} sidecar ===
// NESTED-aware optimization (CHECK_PHASE_NESTED=1) prevents polynomial wall-clock blowup when
// peer chain-guards recursively invoke this validator. Preserves standalone semantics.
// isPeer threshold: phaseNum >= 67 -- peer validators run their own chain-guards (600s timeout).
const NESTED = process.env.CHECK_PHASE_NESTED === '1';
for (const phaseNum of [...CHAIN_PHASES, ...CHAIN_EXTRA]) {
  if (CHAIN_SKIP.has(phaseNum)) continue;
  checks.push({
    id: `CHAIN-${phaseNum}`,
    name: `V-153-CHAIN-${phaseNum}: check-phase-${phaseNum}.mjs exits 0 (CHAIN regression-guard)`,
    run() {
      if (NESTED) {
        return { pass: true, skipped: true, detail: 'nested invocation (CHECK_PHASE_NESTED=1): skip recursive chain-guard expansion' };
      }
      const path = `scripts/validation/check-phase-${phaseNum}.mjs`;
      if (!existsSync(join(process.cwd(), path))) {
        // HAZARD FIX 3: a non-existent chain child is a FAIL, not a graceful skip -- the array is a
        // fixed, asserted span; a member missing from disk is a deleted-predecessor-validator regression.
        return { pass: false, detail: path + ' is absent -- deleted predecessor validator regression (a member of the fixed 105-entry CHAIN_PHASES span must exist on disk)' };
      }
      const isPeer = phaseNum >= 67;
      const subTimeout = isPeer ? 600000 : 300000;
      const subEnv = { ...process.env, CHECK_PHASE_NESTED: '1' };
      try {
        execFileSync('node', [path], {
          stdio: 'pipe',
          timeout: subTimeout,
          maxBuffer: SUBPROCESS_MAX_BUFFER,
          cwd: process.cwd(),
          env: subEnv,
        });
        return { pass: true, detail: 'check-phase-' + phaseNum + ' exits 0' + (isPeer ? ' (nested)' : '') };
      } catch (err) {
        const stderr = err.stderr ? err.stderr.toString() : '';
        const stdout = err.stdout ? err.stdout.toString() : '';
        // HAZARD FIX 2: classification narrowed to the two unambiguous OS-level signals only --
        // ENOENT (file not found) and shell exit status 127 (command not found). A generic stderr
        // substring match would convert a real module-load throw -- exactly what this file's own
        // dedup/length/termini/disjointness guards produce -- into a green SKIP, defeating the
        // apex's own primary safeguard. Everything else falls through to FAIL.
        const isMissing = err.code === 'ENOENT' || err.status === 127;
        if (isMissing) return { pass: true, skipped: true, detail: 'node executable unavailable (ENOENT/127) -- skipped' };
        return { pass: false, detail: execFailDetail(stdout, stderr, { n: 500, trim: true, prefix: 'check-phase-' + phaseNum + ' FAIL: ' }) };
      }
    }
  });
}

// === V-153-SELF: dual-invariant guard (CHAIN_PHASES excludes 153; CHAIN_SKIP empty) ===
// Asserts two invariants:
//   1. CHAIN_PHASES must NOT include 153 (apex [48..N-1] invariant; self-reference is a FAIL)
//   2. CHAIN_SKIP must be empty Set (Phase 68 7b635ca invariant)
checks.push({
  id: 'SELF',
  name: 'V-153-SELF: CHAIN_PHASES does NOT include 153; CHAIN_SKIP is empty Set',
  run() {
    if (CHAIN_PHASES.includes(153)) {
      return { pass: false, detail: 'CHAIN_PHASES includes 153 -- self-reference regression' };
    }
    if (CHAIN_SKIP.size !== 0) {
      const skipList = [...CHAIN_SKIP].join(',');
      return { pass: false, detail: 'CHAIN_SKIP non-empty (' + skipList + ') -- Phase 68 7b635ca empty-Set invariant violated' };
    }
    return { pass: true, detail: 'CHAIN_PHASES = [48..152] (105 entries; 153 absent); CHAIN_SKIP = [] (Phase 68 7b635ca invariant)' };
  }
});

// === Runner loop (verbatim pattern from check-phase-144.mjs) ===
const LABEL_WIDTH = 60;
function padLabel(s) {
  if (s.length >= LABEL_WIDTH) return s + ' ';
  return s + ' ' + '.'.repeat(LABEL_WIDTH - s.length) + ' ';
}

let passed = 0, failed = 0, skipped = 0;
console.log('check-phase-153 -- Phase 153 deliverables (Harness Close -- V120 Pin, C17 Frozen-Aware Residue & 19th Path-A Lineage Bump)\n');
for (const check of checks) {
  let result;
  try { result = check.run(); } catch (e) { result = { pass: false, detail: 'Unexpected error: ' + e.message }; }
  const prefix = '[' + check.id + '/' + checks.length + '] ' + check.name;
  const showDetail = result.detail && (VERBOSE || !result.pass || result.skipped);
  if (result.skipped) {
    skipped++;
    process.stdout.write(padLabel(prefix) + 'SKIPPED' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else if (result.pass) {
    passed++;
    process.stdout.write(padLabel(prefix) + 'PASS' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else {
    failed++;
    process.stdout.write(padLabel(prefix) + 'FAIL -- ' + result.detail + '\n');
  }
}

process.stdout.write('\nResult: ' + passed + ' PASS, ' + failed + ' FAIL, ' + skipped + ' SKIPPED (total checks: ' + checks.length + ')\n');
process.exit(failed > 0 ? 1 : 0);
