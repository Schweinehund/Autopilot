// check-phase-144.mjs -- Phase 144 deliverables (v1.20 V119 Pin + 18th Path-A Lineage Bump + Terminal Close)
//
// Chain-apex of v1.20 -- HARN-18. Ships the v1.20 chain-apex validator: a 96-entry chain spanning
// every integer 48 through 143, HARNESS repointed to v1.20-milestone-audit.mjs. Structural template
// only from check-phase-138.mjs (AUDIT + CHAIN + AUDIT-HARNESS + SELF) -- the chain array and its
// module-load guards are INDEPENDENTLY RE-DERIVED here, never transcribed forward (D-08/D-12). The
// three HAZARD FIXes present in check-phase-138.mjs are INHERITED as MECHANISM, not re-invented, but
// every count and span string they emit is re-derived at authoring time (D-12) -- see below.
// Source of truth: .planning/phases/144-v119-pin-18th-path-a-lineage-bump-terminal-close/144-CONTEXT.md
//   and .planning/phases/144-v119-pin-18th-path-a-lineage-bump-terminal-close/144-PATTERNS.md
//
// CRITICAL -- [48..N-1] invariant: the chain array spans 48..143 (NOT 48..144, which would include
// phase 144 itself, tripping V-144-SELF self-reference FAIL; NOT a truncated range, which would fail
// the length!==96 / terminus!==143 throws). 143 minus 48 plus 1 = 96 entries, GENERATED by arithmetic
// (Array.from), never hand-transcribed or copied from check-phase-138's 90-entry array (D-08/D-25 --
// the owner-ratified correction of a [48..138] drafting error surviving at two ratified sites).
//
// CRITICAL -- CHAIN_SKIP invariant: CHAIN_SKIP = new Set([]) -- NEVER add entries.
// V-144-SELF hard-asserts CHAIN_SKIP.size === 0 per Phase 68 7b635ca invariant, carried forward
// unchanged into v1.20.
//
// CRITICAL -- CHAIN_EXTRA disjointness guard (D-09, NEW in this apex -- the predecessor cannot have
// it): CHAIN_EXTRA = [30, 31] carries forward VERBATIM, stays outside all three CHAIN_PHASES
// module-load guards (dedup/length/termini) and outside V-144-SELF's dual-invariant, exactly as
// check-phase-138.mjs keeps it. But CHAIN_EXTRA is declared AFTER those three guards, so it is
// structurally uncoverable by them -- a sidecar member silently absorbed into CHAIN_PHASES (or vice
// versa) would pass all three. This file adds the fourth guard: assert at module load that every
// CHAIN_EXTRA member is absent from CHAIN_PHASES. Collapsing CHAIN_EXTRA into the span is forbidden.
//
// CRITICAL -- AUDIT-HARNESS existence-before-NESTED ordering: the AUDIT-HARNESS step's existsSync-
// absent branch is a hard FAIL and sits BEFORE the NESTED guard, so an ordering slip becomes a
// recorded FAIL, not a silently skipped regression (D-10/D-13).
//
// CRITICAL -- archive-root token (D-15): this apex asserts the LITERAL STRING token 'v1.20-phases'
// (v1.20's own archival root -- where 144-VERIFICATION.md will land when a future
// /gsd-complete-milestone archives v1.20 at v1.21's close). The resolver's null-vs-success behavior is
// explicitly NOT used as the wrong-token detector: _lib/archive-path.mjs:23-24 checks the LIVE path
// first and returns success regardless of token correctness before archival -- proven by counterexample
// check-phase-125.mjs:86, which carries the wrong ['v1.15-phases'] token and has been permanently green
// with a false detail string for two milestones. Never copy a predecessor's token.
//
// HAZARD FIX 1 (inherited mechanism, D-12) -- explicit maxBuffer on execFileSync: sets
// maxBuffer: 20 * 1024 * 1024 (20 MiB) -- generous headroom for the most verbose single child (the
// AUDIT-HARNESS step running the 16-check v1.20-milestone-audit.mjs --verbose, counted directly off
// the live checks array at authoring time, not copied from any predecessor's stale count) without
// masking a genuinely runaway process.
//
// HAZARD FIX 2 (inherited mechanism, D-12) -- narrowed missing-child classifier: restricts
// classification to the two unambiguous OS-level signals -- ENOENT (file not found) and shell exit
// status 127 (command not found). Everything else -- including a module-load throw from one of THIS
// file's own dedup/length/termini/disjointness guards firing inside a child process -- falls through
// to FAIL, rather than being converted into a green SKIP by a loose stderr-substring heuristic.
//
// HAZARD FIX 3 (inherited mechanism, D-12) -- non-existent chain child is a FAIL, not a skip:
// CHAIN_PHASES is a fixed, asserted 96-entry span; a member of it missing from disk is a regression
// (a deleted predecessor validator), not a benign gap. This is why leaves 139-143 MUST be authored
// before this apex (D-11) -- apex-first would emit five FAILs indistinguishable from a real regression.
//
// Assertion classes:
//   V-144-AUDIT            144-VERIFICATION.md heading-presence via ['v1.20-phases'] resolver (SKIP-PASS
//                          is legitimate pre-close-gate, not a throw)
//   V-144-CHAIN-{48..143}  96 subprocesses; each check-phase-{N}.mjs exits 0 (NESTED-aware)
//   V-144-CHAIN-{30,31}    2 sidecar subprocesses (CHAIN_EXTRA), same shape, disjoint from the span
//   V-144-AUDIT-HARNESS    scripts/validation/v1.20-milestone-audit.mjs exits 0 (current-milestone
//                          harness; NESTED-aware; absent branch precedes the NESTED guard, D-13)
//   V-144-SELF             CHAIN_PHASES does NOT include 144 AND CHAIN_SKIP is empty Set (dual-invariant)
//
// Executed children: 98 (96 CHAIN_PHASES + 2 CHAIN_EXTRA). Total checks: 101 (1 AUDIT + 98 chain +
// 1 AUDIT-HARNESS + 1 SELF).
// Expected result triples (D-10), exact:
//   100 PASS, 0 FAIL, 1 SKIPPED   -- while 144-VERIFICATION.md does not yet exist (AUDIT SKIP-PASSES)
//   101 PASS, 0 FAIL, 0 SKIPPED   -- once 144-VERIFICATION.md exists
//    99 PASS, 1 FAIL, 1 SKIPPED   -- if run before v1.20-milestone-audit.mjs exists (AUDIT-HARNESS FAILs,
//                                     its existence branch precedes the NESTED guard)
// This apex sets CHECK_PHASE_NESTED=1 on every child it spawns -- it structurally cannot produce, and
// must never be described as producing, a result across a non-nested chain (D-32).
//
// Timeout budgets (inherited mechanism, D-12): 600s per-peer (phaseNum >= 67) / 300s per-subprocess,
// and the AUDIT-HARNESS 300s timeout. This apex is NEVER added to its own CHAIN_PHASES -- that is the
// exact self-reference V-144-SELF hard-fails on.
//
// Lineage: structural template check-phase-138.mjs (v1.19's apex); chain span, guards and every
// runtime-emitted literal independently re-derived this phase (D-08/D-12).
//
// Run the apex chain SEPARATELY from any verifier or prose-guard pass (D-35) -- a link/anchor edit is
// a prose change and has tripped banned-phrase guards after a passed verifier before.
//
// Usage: node scripts/validation/check-phase-144.mjs [--verbose]
// Exit code: 0 if all PASS or SKIPPED; 1 if any FAIL.

import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import process from 'node:process';
import { resolveArchivedPhasePath } from './_lib/archive-path.mjs';
import { execFailDetail } from './_lib/exec-fail-detail.mjs';

const argv = process.argv.slice(2);
const VERBOSE = argv.includes('--verbose');

function readFile(relPath) {
  const abs = join(process.cwd(), relPath);
  if (!existsSync(abs)) return null;
  return readFileSync(abs, 'utf8').replace(/\r\n/g, '\n');
}

const HARNESS = 'scripts/validation/v1.20-milestone-audit.mjs';

// HAZARD FIX 1: explicit maxBuffer (20 MiB) -- see header comment for the chosen-value rationale.
const SUBPROCESS_MAX_BUFFER = 20 * 1024 * 1024;

// Phase 144 chain-apex spans every integer 48..143 (143 - 48 + 1 = 96 entries).
// GENERATED by arithmetic, not hand-transcribed or copied from check-phase-138's 90-entry array (D-08).
const CHAIN_START = 48;
const CHAIN_END = 143; // [48..N-1] invariant for N=144: apex EXCLUDES its own phase (144).
const CHAIN_PHASES = Array.from({ length: CHAIN_END - CHAIN_START + 1 }, (_, i) => CHAIN_START + i);

// CHAIN_SKIP topology: empty per Phase 68 7b635ca invariant -- no entries to suppress.
// NEVER add entries: V-144-SELF hard-asserts CHAIN_SKIP.size === 0.
const CHAIN_SKIP = new Set([]);

// De-duplication guard: length + termini asserts alone do not catch a duplicated/dropped interior
// entry. Assert the set of unique values also has exactly 96 members.
if (new Set(CHAIN_PHASES).size !== CHAIN_PHASES.length) {
  throw new Error('check-phase-144 CHAIN_PHASES contains duplicate entries (unique count ' + new Set(CHAIN_PHASES).size + ' !== ' + CHAIN_PHASES.length + ')');
}

// Programmatic bound assertions (fail-loud at module load if the chain topology drifts):
// CHAIN_PHASES must be exactly 96 entries and terminate at 143 (the [48..N-1] invariant for N=144).
if (CHAIN_PHASES.length !== 96) {
  throw new Error('check-phase-144 CHAIN_PHASES length ' + CHAIN_PHASES.length + ' !== 96 (integers 48..143 inclusive)');
}
if (CHAIN_PHASES[0] !== 48 || CHAIN_PHASES[CHAIN_PHASES.length - 1] !== 143) {
  throw new Error('check-phase-144 CHAIN_PHASES must span 48..143 (got ' + CHAIN_PHASES[0] + '..' + CHAIN_PHASES[CHAIN_PHASES.length - 1] + ')');
}

const checks = [];

// V-144-AUDIT: heading-presence check on 144-VERIFICATION.md (SKIP-PASS until the close-gate lands).
// Uses this milestone's OWN, objectively correct archive-root token ['v1.20-phases'] -- asserted as a
// LITERAL STRING here, a deliberate correction away from the predecessor-copied wrong tokens that
// check-phase-119/125/128 carry (frozen, not fixed here). resolveArchivedPhasePath's resolver-null ->
// SKIP-PASS is legitimate pre-close-gate behavior, NOT the silent-wrong bug class D-15 guards against
// -- the resolver checks the LIVE path first and succeeds regardless of token correctness before
// archival, so a WRONG token would only be exposed post-archival, permanently (D-15's
// check-phase-125.mjs:86 counterexample). Getting the token objectively right at authoring time is
// what keeps this SKIP-PASS branch honest.
const ARCHIVE_ROOT_TOKEN = 'v1.20-phases';
checks.push({
  id: 'AUDIT',
  name: 'V-144-AUDIT: 144-VERIFICATION.md exists and contains Phase 144 verification heading',
  run() {
    const verifPath = resolveArchivedPhasePath(
      '144-v119-pin-18th-path-a-lineage-bump-terminal-close/144-VERIFICATION.md',
      [ARCHIVE_ROOT_TOKEN]
    );
    const verif = verifPath ? readFile(verifPath) : null;
    if (!verif) return { pass: true, skipped: true, detail: '144-VERIFICATION.md not yet authored (PASS-via-skip until the Phase 144 close-gate lands; correct-token resolver-null is legitimate pre-close-gate)' };
    if (!/Phase 144/i.test(verif)) {
      return { pass: false, detail: '144-VERIFICATION.md missing "Phase 144" section heading' };
    }
    return { pass: true, detail: '144-VERIFICATION.md exists with Phase 144 verification content' };
  }
});

// CHAIN_EXTRA: carried forward verbatim from check-phase-138.mjs (D-09) -- NOT part of the arithmetic
// CHAIN_PHASES span and NOT subject to its three module-load guards (dedup/length/termini) above, nor
// to V-144-SELF's two invariants below -- both stay scoped to CHAIN_PHASES/CHAIN_SKIP only.
const CHAIN_EXTRA = [30, 31];

// NEW guard 144 adds that 138 structurally cannot have (D-09): CHAIN_EXTRA is declared AFTER all
// three CHAIN_PHASES guards above, so a sidecar member silently absorbed into (or overlapping) the
// span would pass all three undetected. Assert disjointness explicitly, at module load.
if (!CHAIN_EXTRA.every((n) => !CHAIN_PHASES.includes(n))) {
  throw new Error('check-phase-144 CHAIN_EXTRA overlaps CHAIN_PHASES -- must stay disjoint');
}

// === V-144-CHAIN-NN: chain regression-guards for check-phase-{48..143}.mjs plus the {30,31} sidecar ===
// NESTED-aware optimization (CHECK_PHASE_NESTED=1) prevents polynomial wall-clock blowup when
// peer chain-guards recursively invoke this validator. Preserves standalone semantics.
// isPeer threshold: phaseNum >= 67 -- peer validators run their own chain-guards (600s timeout).
const NESTED = process.env.CHECK_PHASE_NESTED === '1';
for (const phaseNum of [...CHAIN_PHASES, ...CHAIN_EXTRA]) {
  if (CHAIN_SKIP.has(phaseNum)) continue;
  checks.push({
    id: `CHAIN-${phaseNum}`,
    name: `V-144-CHAIN-${phaseNum}: check-phase-${phaseNum}.mjs exits 0 (CHAIN regression-guard)`,
    run() {
      if (NESTED) {
        return { pass: true, skipped: true, detail: 'nested invocation (CHECK_PHASE_NESTED=1): skip recursive chain-guard expansion' };
      }
      const path = `scripts/validation/check-phase-${phaseNum}.mjs`;
      if (!existsSync(join(process.cwd(), path))) {
        // HAZARD FIX 3: a non-existent chain child is a FAIL, not a graceful skip -- the array is a
        // fixed, asserted span; a member missing from disk is a deleted-predecessor-validator regression.
        return { pass: false, detail: path + ' is absent -- deleted predecessor validator regression (a member of the fixed 96-entry CHAIN_PHASES span must exist on disk)' };
      }
      const isPeer = phaseNum >= 67;
      const subTimeout = isPeer ? 600000 : 300000;
      const subEnv = { ...process.env, CHECK_PHASE_NESTED: '1' };
      try {
        execFileSync('node', [path], {
          stdio: 'pipe',
          timeout: subTimeout,
          maxBuffer: SUBPROCESS_MAX_BUFFER,
          cwd: process.cwd(),
          env: subEnv,
        });
        return { pass: true, detail: 'check-phase-' + phaseNum + ' exits 0' + (isPeer ? ' (nested)' : '') };
      } catch (err) {
        const stderr = err.stderr ? err.stderr.toString() : '';
        const stdout = err.stdout ? err.stdout.toString() : '';
        // HAZARD FIX 2: classification narrowed to the two unambiguous OS-level signals only --
        // ENOENT (file not found) and shell exit status 127 (command not found). A generic stderr
        // substring match would convert a real module-load throw -- exactly what this file's own
        // dedup/length/termini/disjointness guards produce -- into a green SKIP, defeating the
        // apex's own primary safeguard. Everything else falls through to FAIL.
        const isMissing = err.code === 'ENOENT' || err.status === 127;
        if (isMissing) return { pass: true, skipped: true, detail: 'node executable unavailable (ENOENT/127) -- skipped' };
        return { pass: false, detail: execFailDetail(stdout, stderr, { n: 500, trim: true, prefix: 'check-phase-' + phaseNum + ' FAIL: ' }) };
      }
    }
  });
}

// === V-144-AUDIT-HARNESS: v1.20-milestone-audit.mjs subprocess exits 0 (current-milestone harness) ===
checks.push({
  id: 'AUDIT-HARNESS',
  name: 'V-144-AUDIT-HARNESS: v1.20-milestone-audit.mjs exits 0 (current-milestone harness)',
  run() {
    if (!existsSync(join(process.cwd(), HARNESS))) {
      // Mirrors HAZARD FIX 3's reasoning: the current-milestone harness is a mandatory, not optional,
      // deliverable of this same close phase -- if it is absent, that is a regression, not a skip.
      // This branch precedes the NESTED guard below (D-10/D-13): an ordering slip records a FAIL.
      return { pass: false, detail: HARNESS + ' is absent -- current-milestone harness regression' };
    }
    if (NESTED) {
      return { pass: true, skipped: true, detail: 'nested invocation (CHECK_PHASE_NESTED=1): skip AUDIT-HARNESS re-run against evolved corpus' };
    }
    try {
      execFileSync('node', [HARNESS], { stdio: 'pipe', timeout: 300000, maxBuffer: SUBPROCESS_MAX_BUFFER, cwd: process.cwd() });
      return { pass: true, detail: 'v1.20-milestone-audit.mjs exits 0 (current-milestone harness)' };
    } catch (err) {
      const stderr = err.stderr ? err.stderr.toString() : '';
      const stdout = err.stdout ? err.stdout.toString() : '';
      const isMissing = err.code === 'ENOENT' || err.status === 127;
      if (isMissing) return { pass: true, skipped: true, detail: 'node executable unavailable (ENOENT/127) -- skipped' };
      return { pass: false, detail: execFailDetail(stdout, stderr, { n: 300, trim: false, prefix: 'harness FAIL: ' }) };
    }
  }
});

// === V-144-SELF: dual-invariant guard (CHAIN_PHASES excludes 144; CHAIN_SKIP empty) ===
// Asserts two invariants:
//   1. CHAIN_PHASES must NOT include 144 (apex [48..N-1] invariant; self-reference is a FAIL)
//   2. CHAIN_SKIP must be empty Set (Phase 68 7b635ca invariant)
checks.push({
  id: 'SELF',
  name: 'V-144-SELF: CHAIN_PHASES does NOT include 144; CHAIN_SKIP is empty Set',
  run() {
    if (CHAIN_PHASES.includes(144)) {
      return { pass: false, detail: 'CHAIN_PHASES includes 144 -- self-reference regression' };
    }
    if (CHAIN_SKIP.size !== 0) {
      const skipList = [...CHAIN_SKIP].join(',');
      return { pass: false, detail: 'CHAIN_SKIP non-empty (' + skipList + ') -- Phase 68 7b635ca empty-Set invariant violated' };
    }
    return { pass: true, detail: 'CHAIN_PHASES = [48..143] (96 entries; 144 absent); CHAIN_SKIP = [] (Phase 68 7b635ca invariant)' };
  }
});

// === Runner loop (verbatim pattern from check-phase-138.mjs) ===
const LABEL_WIDTH = 60;
function padLabel(s) {
  if (s.length >= LABEL_WIDTH) return s + ' ';
  return s + ' ' + '.'.repeat(LABEL_WIDTH - s.length) + ' ';
}

let passed = 0, failed = 0, skipped = 0;
console.log('check-phase-144 -- Phase 144 deliverables (v1.20 V119 Pin + 18th Path-A Lineage Bump + Terminal Close)\n');
for (const check of checks) {
  let result;
  try { result = check.run(); } catch (e) { result = { pass: false, detail: 'Unexpected error: ' + e.message }; }
  const prefix = '[' + check.id + '/' + checks.length + '] ' + check.name;
  const showDetail = result.detail && (VERBOSE || !result.pass || result.skipped);
  if (result.skipped) {
    skipped++;
    process.stdout.write(padLabel(prefix) + 'SKIPPED' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else if (result.pass) {
    passed++;
    process.stdout.write(padLabel(prefix) + 'PASS' + (showDetail ? ' -- ' + result.detail : '') + '\n');
  } else {
    failed++;
    process.stdout.write(padLabel(prefix) + 'FAIL -- ' + result.detail + '\n');
  }
}

process.stdout.write('\nResult: ' + passed + ' PASS, ' + failed + ' FAIL, ' + skipped + ' SKIPPED (total checks: ' + checks.length + ')\n');
process.exit(failed > 0 ? 1 : 0);
